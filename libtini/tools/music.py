#!/usr/bin/env python3
"""Compile a device-tick event score or a pattern song to borrowed C data.

An event score has "events" and becomes ti_music_event entries. A pattern
song has "song" and becomes the byte layout that ti_song_start reads; see
docs/reference/formats.html#song.
"""
import argparse
import json
from pathlib import Path
import re


def compile_score(document, symbol="score"):
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", symbol):
        raise ValueError("symbol must be a C identifier")
    voices = document.get("voices", 6)
    if voices not in (6, 12):
        raise ValueError("voices must be 6 or 12")
    events = document.get("events")
    if not isinstance(events, list) or not 1 <= len(events) <= 512:
        raise ValueError("events must contain 1..512 entries")
    rows = []
    ticks = 0
    for event in events:
        if not isinstance(event, dict) or set(event) != {"duration", "period", "voice", "volume"}:
            raise ValueError("each event needs duration, period, voice and volume")
        limits = (("duration", 65535), ("period", 2047), ("voice", voices - 1), ("volume", 15))
        values = []
        for key, maximum in limits:
            value = event[key]
            if type(value) is not int or not 0 <= value <= maximum:
                raise ValueError(key + " out of range")
            values.append(value)
        ticks += values[0]
        rows.append("    {" + ", ".join(map(str, values)) + "}")
    if ticks == 0:
        raise ValueError("score must advance device time")
    # The foreground driver bounds each update to 32 due events.
    consecutive = 0
    for event in events:
        consecutive = consecutive + 1 if event["duration"] == 0 else 0
        if consecutive >= 32:
            raise ValueError("too many simultaneous events for one audio update")
    text = ('/* Generated by tools/music.py; durations use nominal device ticks. */\n'
            '#include "libtini/audio.h"\n'
            'static const ti_music_event ' + symbol + '[] = {\n' + ',\n'.join(rows) + '\n};\n'
            '#define ' + symbol.upper() + '_COUNT ' + str(len(rows)) + '\n')
    return text, {"voices": voices, "events": len(rows), "ticks": ticks,
                  "event_bytes": len(rows) * 6, "nominal_ticks_per_second": 100,
                  "clock_calibration_required": True}


# Pattern bytes. ti_song_start rejects every other value.
REST, TIE, LENGTH, VOLUME, DECAY, FLOOR, END = 0x60, 0x61, 0x80, 0xC0, 0xD0, 0xE0, 0xFF
MAX_NOTES, MAX_LENGTH, MAX_TRACKS = 96, 64, 12
NOTE_NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def note_number(name):
    """MIDI note number of a name such as C4 (60), F#3 or Bb5."""
    match = re.fullmatch(r"([A-G])([#b]?)(-?\d)", name)
    if not match:
        raise ValueError("bad note " + repr(name))
    letter, accidental, octave = match.groups()
    return (int(octave) + 1) * 12 + NOTE_NAMES[letter] + {"": 0, "#": 1, "b": -1}[accidental]


def note_period(number):
    """AY tone period of an equal-tempered note at the nominal 1 MHz base clock."""
    period = round(1_000_000 / (16 * 440 * 2 ** ((number - 69) / 12)))
    if not 1 <= period <= 2047:
        raise ValueError(f"note {number} needs period {period}, outside 1..2047")
    return period


def small(value, what, maximum=15):
    if type(value) is not int or not 0 <= value <= maximum:
        raise ValueError(f"{what} must be 0..{maximum}")
    return value


def parse_pattern(name, text):
    """Tokens: NOTE:ROWS, -:ROWS (rest), ^:ROWS (hold), vN, dN, fN."""
    if not isinstance(text, str):
        raise ValueError("pattern " + name + " must be a string")
    tokens = []
    for token in text.split():
        command = re.fullmatch(r"([vdf])(\d+)", token)
        if command:
            tokens.append((command.group(1), small(int(command.group(2)), name + " " + token)))
            continue
        row = re.fullmatch(r"([^:]+):(\d+)", token)
        if not row or not 1 <= int(row.group(2)) <= 255:
            raise ValueError(f"pattern {name}: bad token {token!r}")
        symbol, rows = row.group(1), int(row.group(2))
        tokens.append(("row", symbol if symbol in ("-", "^") else note_number(symbol), rows))
    if not any(token[0] == "row" for token in tokens):
        raise ValueError("pattern " + name + " has no rows")
    return tokens


def compile_song(document, symbol="song"):
    """Return C text and a report for a {"song": ...} document."""
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", symbol):
        raise ValueError("symbol must be a C identifier")
    song = document.get("song")
    if not isinstance(song, dict):
        raise ValueError("song must be an object")
    bpm, per_beat = song.get("bpm"), song.get("rows_per_beat")
    if not isinstance(bpm, (int, float)) or isinstance(bpm, bool) or not 20 <= bpm <= 400:
        raise ValueError("bpm must be 20..400")
    if type(per_beat) is not int or not 1 <= per_beat <= 16:
        raise ValueError("rows_per_beat must be 1..16")
    # Device ticks per row in 8.8 fixed point; the player adds the fraction.
    row_ticks = round(100 * 60 / (bpm * per_beat) * 256)
    if not 256 <= row_ticks <= 100 * 256:
        raise ValueError("a row must last 1..100 device ticks")
    tracks, patterns = song.get("tracks"), song.get("patterns")
    if not isinstance(tracks, list) or not 1 <= len(tracks) <= MAX_TRACKS:
        raise ValueError(f"tracks must list 1..{MAX_TRACKS} tracks")
    if not isinstance(patterns, dict) or not patterns:
        raise ValueError("patterns must name at least one pattern")
    parsed = {name: parse_pattern(name, text) for name, text in patterns.items()}
    length = None
    for track in tracks:
        if not isinstance(track, dict) or not set(track) <= {"name", "volume", "decay", "floor", "order"}:
            raise ValueError("each track has name, volume, decay, floor and order")
        order = track.get("order")
        if not isinstance(order, list) or not order or not all(item in parsed for item in order):
            raise ValueError("track order must list defined patterns")
        if length is None:
            length = len(order)
        elif len(order) != length:
            raise ValueError("every track order needs the same number of positions")
    if length > 255:
        raise ValueError("orders hold at most 255 positions")
    loop = song.get("loop", 0)
    if type(loop) is not int or not 0 <= loop < length:
        raise ValueError("loop must be an order position")

    used = sorted({token[1] for tokens in parsed.values() for token in tokens
                   if token[0] == "row" and isinstance(token[1], int)})
    if len(used) > MAX_NOTES:
        raise ValueError(f"a song may use at most {MAX_NOTES} distinct notes")
    index = {number: i for i, number in enumerate(used)}
    periods = [note_period(number) for number in used]

    # Only patterns that some order uses are emitted.
    names = []
    for track in tracks:
        for item in track["order"]:
            if item not in names:
                names.append(item)
    if len(names) > 255:
        raise ValueError("a song may use at most 255 patterns")
    bodies = []
    for name in names:
        body, current = bytearray(), None
        for token in parsed[name]:
            if token[0] != "row":
                body.append({"v": VOLUME, "d": DECAY, "f": FLOOR}[token[0]] | token[1])
                continue
            _, what, rows = token
            first = True
            # Longer rows continue as holds of at most 64 rows each.
            while rows:
                step = min(rows, MAX_LENGTH)
                if step != current:
                    body.append(LENGTH | (step - 1))
                    current = step
                body.append(REST if what == "-" else TIE if what == "^" or not first else index[what])
                rows -= step
                first = False
        body.append(END)
        bodies.append(bytes(body))

    header = bytearray(row_ticks.to_bytes(2, "little"))
    header += bytes((len(tracks), length, loop, len(periods), len(names)))
    for track in tracks:
        header += bytes((small(track.get("volume", 12), "volume"), small(track.get("decay", 0), "decay"),
                         small(track.get("floor", 0), "floor")))
    for period in periods:
        header += period.to_bytes(2, "little")
    offset = len(header) + 2 * len(names) + len(tracks) * length
    for body in bodies:
        header += offset.to_bytes(2, "little")
        offset += len(body)
    for track in tracks:
        header += bytes(names.index(item) for item in track["order"])
    data = bytes(header) + b"".join(bodies)
    if len(data) > 65535:
        raise ValueError("song exceeds 65535 bytes")

    rows_per_track = [sum(token[2] for item in track["order"] for token in parsed[item] if token[0] == "row")
                      for track in tracks]
    if len(set(rows_per_track)) != 1:
        raise ValueError("every track must last the same number of rows: " + str(rows_per_track))
    lines = [", ".join(f"0x{byte:02X}" for byte in data[i:i + 16]) for i in range(0, len(data), 16)]
    credit = document.get("credit")
    comment = "/* Generated by tools/music.py from a pattern song; see docs/reference/formats.html#song."
    if isinstance(credit, str) and credit:
        comment += "\n * " + credit.replace("*/", "* /")
    text = (comment + " */\n#include <stdint.h>\n"
            "static const uint8_t " + symbol + "[] = {\n    " + ",\n    ".join(lines) + "\n};\n"
            "#define " + symbol.upper() + "_SIZE " + str(len(data)) + "\n")
    seconds = rows_per_track[0] * row_ticks / 256 / 100
    return text, {"tracks": len(tracks), "positions": length, "loop": loop, "patterns": len(names),
                  "notes": len(periods), "rows": rows_per_track[0], "row_ticks_8_8": row_ticks,
                  "nominal_seconds": round(seconds, 2), "bytes": len(data),
                  "pattern_bytes": sum(map(len, bodies)), "nominal_ticks_per_second": 100,
                  "clock_calibration_required": True}


def compile_document(document, symbol):
    return compile_song(document, symbol) if "song" in document else compile_score(document, symbol)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--symbol", default="score")
    parser.add_argument("--report", type=Path)
    parser.add_argument("--preview", action="store_true", help="print event timing; no host synthesizer")
    args = parser.parse_args()
    try:
        document = json.loads(args.source.read_text(encoding="utf-8"))
        output, report = compile_document(document, args.symbol)
    except (ValueError, KeyError, TypeError) as error:
        raise SystemExit(str(error)) from None
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n")
    if args.preview or not args.output:
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
