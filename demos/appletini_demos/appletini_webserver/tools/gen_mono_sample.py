"""Regenerate the original local demo picture; requires Pillow."""
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1]
image = Image.new('P', (252, 128))
image.putpalette([c for n in range(256) for c in (n, n, n)])
pixels = image.load()
for y in range(128):
    for x in range(252):
        pixels[x, y] = 240 - y
draw = ImageDraw.Draw(image)
draw.ellipse((165, 12, 207, 54), fill=255)
draw.polygon([(0, 110), (55, 28), (104, 105), (160, 50), (225, 112), (251, 73), (251, 127), (0, 127)], fill=55)
draw.polygon([(55, 28), (36, 56), (55, 49), (70, 56)], fill=250)
draw.rectangle((0, 111, 251, 127), fill=170)
for y in range(114, 128, 4):
    draw.line((0, y, 251, y), fill=100)
image = image.resize((126, 64), Image.Resampling.NEAREST)
image = image.convert('RGB').quantize(colors=8, dither=Image.Dither.NONE)
stream = BytesIO()
image.save(stream, 'GIF', optimize=True)
data = stream.getvalue()
lines = ['/* Generated by tools/gen_mono_sample.py. SPDX-License-Identifier: MIT */',
         'const unsigned char mono_sample[] = {']
lines += ['    ' + ','.join(f'0x{b:02x}' for b in data[i:i+16]) + ','
          for i in range(0, len(data), 16)]
lines += ['};', f'const unsigned int mono_sample_length = {len(data)};', '']
(root / 'mono_sample.h').write_text('\n'.join(lines), encoding='ascii')
print(f'mono_sample.h: {len(data)} GIF bytes')
