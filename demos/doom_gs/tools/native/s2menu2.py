def _cut_script(stop_after: str) -> str:
    """menus.script up to the line `stop_after` (kept), then a 3 s wait
    and the stop."""
    text = (ROOT / 'coverage' / 'm11' / 'menus.script').read_text()
    at = text.index(stop_after)
    return text[:at] + stop_after + '\nat +3s stop\n'


def bench_script() -> str:
    return ('# the menu over the title, its frame redrawn whole with the\n'
            '# benchmark\'s result poked (tools/native/s2menu2.py)\n'
            'wait d_main65.s:pagedrawn == 1 within 90s\n'
            'at +10f press escape\n'
            'wait _g_menuactive == 1 within 10s\n'
            'wait m_menu65.s:messageToPrint == 1 within 10s\n'
            'at +3s stop\n')


def _poke_lines(point: str, items: Sequence[Tuple[int, bytes]]) -> List[str]:
    out = []
    for at, data in items:
        for off in range(0, len(data), 64):
            out.append('%s %06X %s' % (point, at + off,
                                       data[off:off + 64].hex()))
    return out


def pokes(run: str) -> Tuple[str, str]:
    """(the script, the poke file) of a run."""
    from native import s2cap as C, s2state as T
    names, table = T.apple2e_keys()
    ui = C.sym('i_viigs65.s:uiDisplay')
    if run == 'k1':
        point = 'pc=%06X,if=%06X:2:eq:%d,hits=1' % (
            ui, C.sym('m_menu65.s:currentMenu'), MENU_KEYS)
        return (_cut_script('wait m_menu65.s:currentMenu == 8 within 10s'),
                T.keys_poke(names, table, point))
    if run == 'k2':
        text = T.keys_poke(names, table)
        # (the names alone: keyTable's lines dropped, each line one range)
        tb = C.sym('i_iigs65.s:keyTable')
        keep = [x for x in text.splitlines() if x.startswith('#') or
                not (tb <= int(x.split()[1], 16) < tb + 256)]
        return ((ROOT / 'coverage' / 'm11' / 'menus.script').read_text(),
                '\n'.join(keep) + '\n')
    if run == 'bench':
        point = 'pc=%06X,if=%06X:2:eq:1,hits=1' % (
            ui, C.sym('m_menu65.s:_g_menuactive'))
        items = [(C.sym('m_menu65.s:messageToPrint'), b'\x01\x00'),
                 (C.sym('m_menu65.s:messageKind'),
                  bytes([MSG_BENCH, 0])),
                 (C.sym('m_menu65.s:menuversion'), b'\x77\x00'),
                 (C.sym('VW_BTXT'), BENCH_TEXT + b'\x00')]
        return (bench_script(),
                '# the benchmark\'s result (tools/native/s2menu2.py)\n' +
                '\n'.join(_poke_lines(point, items)) + '\n')
    raise Menu2Error('no run %s' % run)


def capture(runs: Sequence[str] = RUNS) -> Dict[str, Dict]:
    """Each run on ref816 through part s2cap's capture (the points of
    SCREENS.md 6.1, streamed and distilled) into CASES/<run>, with its
    script and pokes; and s2menu1's call log of menus.script into
    OUT/cap. The runs' files are deleted."""
    import shutil
    import tempfile
    from native import s2cap as C
    C.check_disk(BUILD)
    OUT.mkdir(parents=True, exist_ok=True)
    out = {}
    work = Path(tempfile.mkdtemp(prefix='tmp-cap-', dir=str(OUT)))
    try:
        for run in runs:
            script, poke = pokes(run)
            sp = work / (run + '.script')
            sp.write_text(script)
            pp = work / (run + '.poke')
            pp.write_text(poke)
            idx = C.capture('menus', run_root(run), work_root=work,
                            pokes=pp, script_path=sp)
            if idx['problems']:
                raise Menu2Error('the capture of %s: %s'
                                 % (run, idx['problems'][:3]))
            out[run] = {'frames': len(idx['frames']),
                        'events': len(idx['events'])}
    finally:
        shutil.rmtree(str(work), ignore_errors=True)
    M1.capture()
    return out


def ready_cases(run: str) -> Path:
    from native import s2cap as C
