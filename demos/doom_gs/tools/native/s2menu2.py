def inc_text() -> str:
    ps = M1.patches()
    lines = ['; Generated by tools/native/s2menu2.py --inc (part s2menu2, '
             'docs/m11-parts/s2menu2.md). Do not edit.', '',
             '; drawSlots\' titles centred (centerPatch: 160 - width / 2)']
    for name in ('M_LOADG', 'M_SAVEG'):
        x = title_x(ps[name].width)
        if not 0 <= x < 256:
            raise Menu2Error('%s at x %d' % (name, x))
        lines.append('M2_%s_X     = %d ; %s %d wide' % (name[2:], x, name,
                                                       ps[name].width))
    lines += ['', '; snd_MusicVolume\'s byte in SS_SETTINGS (the field map\'s, '
              'request S2MENU2-2)',
              'SET_MUSVOL      = %d' % settings_places()[MUSIC_FIELD]]
    return '\n'.join(lines) + '\n'


