class MJob(NamedTuple):
    run: str
    page: str                   # what is up: a page's name, or a message
    job: object                 # s2menu1.Job


def page_of(d) -> Tuple[int, int, int]:
    return (M1.uval(d, 'm_menu65.s:currentMenu'),
            M1.uval(d, 'm_menu65.s:messageToPrint'),
            M1.uval(d, 'm_menu65.s:messageKind'))


def page_name(d) -> str:
    menu, msg, kind = page_of(d)
    if msg:
        return 'benchmark' if kind == MSG_BENCH else 'message %d' % kind
    return M1.PAGE_NAMES.get(menu, 'page %d' % menu)


def jobs_of(run: str, setchg: Dict[str, int]) -> List[MJob]:
    """The run's jobs this part compares: run A all of s2menu1's (both
    parts' pages; the key setup's frames redrawn whole excluded, X-K),
    runs K1 and K2 the key setup page's frames, run B the benchmark's."""
    root = ready_cases(run)
    out = []
    for j in M1.menu_jobs(setchg if run == 'a' else {}, root):
        menu, msg, kind = page_of(j.case.before)
        why = ''
        if run == 'a':
            if j.kind == 'full' and not msg and menu == MENU_KEYS:
                why = X_K
            elif msg and kind == MSG_BENCH:
                why = 'the benchmark in run A'      # (never: run B's)
        elif run in ('k1', 'k2'):
            if msg or menu != MENU_KEYS or j.kind not in ('full', 'skull'):
                continue
        elif run == 'bench':
            if not (msg and kind == MSG_BENCH):
                continue
        out.append(MJob(run, page_name(j.case.before),
                        j._replace(excluded=why)))
    return out


def bench_record() -> Tuple:
    """M_BFPS (s2layout's, S2MENU2-1) holding the poked FPS text, and
    M_BROWS after it empty (the play build's phase rows: X2 stays
    black)."""
    at = native_places()['M_BFPS']
    if native_places()['M_BROWS'] != at + dict(MENU2_NATIVE)['M_BFPS']:
        raise Menu2Error('M_BROWS does not follow M_BFPS')
    base = S.SS['SS_MENUW'] - S.OWN_STATE['MENUW'][1]
    return (1, S.S2STATE, base + at,
            BENCH_FPS + bytes(dict(MENU2_NATIVE)['M_BFPS'] -
                              len(BENCH_FPS) +
                              dict(MENU2_NATIVE)['M_BROWS']))


def extra_records(case) -> List[Tuple]:
    """What this part's pages read that s2menu1's injection does not: the
    bindings (keyTable's Doom keys 1:1 into PL_KEYTAB, 6.2), the effects'
    volume (snd_SfxVolume into SND_SFXVOL; s2menu1's sound blocks are
    zeros), the benchmark's FPS text."""
    from native import s2cap as C
    d = case.before
    kt = d.get(C.sym('i_iigs65.s:keyTable'), 256)
    music = settings_places()[MUSIC_FIELD]
    return [(0, 0, S.KEYTAB_PLACE[0], bytes(kt[0::2])),
            (1, S.S2STATE, S.SS['SS_SETTINGS'] + music,
             bytes([M1.uval(d, MUSIC_FIELD) & 0xFF])),
            (2, 0, sfxvol_place(),
             bytes([M1.uval(d, 's_sound65.s:snd_SfxVolume') & 0xFF])),
            bench_record()]


