def on_keys(job) -> bool:
    menu, msg, _ = page_of(job.case.before)
    return not msg and menu == MENU_KEYS


def check_chains(b, setchg: Dict[str, int], data: Dict, jobs: int = 2,
                 work_root: Path = OUT,
                 only: Optional[Sequence[str]] = None) -> Dict:
    saved = (M1.job_records, M1.on_m2)
    M1.job_records, M1.on_m2 = job_records, on_keys
    try:
        return M1.check_chains(b, setchg, data, jobs, work_root, only)
    finally:
        M1.job_records, M1.on_m2 = saved


