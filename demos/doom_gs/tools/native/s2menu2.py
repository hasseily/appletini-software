X2_ROWS = ((92, 99), (108, 115), (124, 131))   # uiBenchmark's rows 3-5


def x2_offsets() -> List[int]:
    from native import s2check as K
    return K.offsets(K.x2(X2_ROWS).region)


class _Case:
    """A case whose screens before and after the frame are the
    reference's with the X2 rows black (what the native shows there: a
    frame after the result's first keeps the black rows its first drew)."""

    def __init__(self, case, before: bytes, after: bytes):
        self._case = case
        self.screen_before = before
        self.screen_after = after

    def __getattr__(self, name):
        return getattr(self._case, name)


def _black(screen: bytes) -> Tuple[bytes, int]:
    out = bytearray(screen)
    drawn = 0
    for a in x2_offsets():
        drawn += out[a - S.SHR] != 0
        out[a - S.SHR] = 0
    return bytes(out), drawn


def expected_job(mj: MJob):
    """The job run and judged: on the benchmark's result, the screens with
    the X2 rows black (s2check's x2), so a byte there not 0 differs;
    (job, X2's bytes, those the reference drew)."""
    if mj.page != 'benchmark':
        return mj.job, 0, 0
    case = mj.job.case
    after, drawn = _black(case.screen_after)
    before, _ = _black(case.screen_before)
    return (mj.job._replace(case=_Case(case, before, after)),
            len(x2_offsets()), drawn)


def key_problems(mj: MJob) -> List[str]:
    """Runs K1 and K2: the reference drew the //e names (both) and the //e
    table (K1), poked 1:1 (SCREENS.md 6.2)."""
    from native import s2cap as C, s2state as T
    if mj.run not in ('k1', 'k2'):
        return []
    names, table = T.apple2e_keys()
    d = mj.job.case.before
    out = []
    want = b''.join(n.encode() + bytes(8 - len(n)) for n in names)
    if d.get(C.sym('m_menu65.s:keyNames'), 1024) != want:
        out.append('the reference\'s keyNames are not the //e names')
    if mj.run == 'k1' and d.get(C.sym('i_iigs65.s:keyTable'), 256) != \
            b''.join(bytes([k, ch]) for k, ch in table):
        out.append('the reference\'s keyTable is not the //e table')
    return out


def check_frames(b, setchg: Dict[str, int], runs: Sequence[str] = (
        'a', 'k1', 'k2', 'bench'), jobs: int = 2, work_root: Path = OUT,
        pick=None) -> Dict:
    """Every job of the runs not excluded, twice (as s2menu1's): fill $A5
    with the write log (the strays, the publish order; an open as a whole
    paused frame), fill $5A with the reference's marked bytes poisoned."""
    import shutil
    import tempfile
    from concurrent.futures import ThreadPoolExecutor
    from native import s2check as K
    work_root.mkdir(parents=True, exist_ok=True)
    all_jobs = [mj for run in runs for mj in jobs_of(run, setchg)]
    js = [mj for mj in all_jobs if not mj.job.excluded and
          (pick is None or pick(mj))]
    root = Path(tempfile.mkdtemp(prefix='tmp-frames-', dir=str(work_root)))

    def one(arg):
        mj, fill, poison = arg
        job = mj.job
        paused = not poison
        work = root / ('%s-%s-%02x' % (mj.run, job.name, fill))
        try:
            ejob, x2n, x2drawn = expected_job(mj)
            recs, screen = job_records(b, ejob, fill, poison)
            r = M1.run_calls(b, recs, [M1.call_of(job, paused)], fill, work,
                             M1.SNAP, write_log=not poison)
            probs, compared = M1.frame_problems(b, ejob, r, fill, poison,
                                                screen)
            probs += key_problems(mj)
            depth = M1.SR_depth(r)
            if depth is not None and depth > S.STACK_2D:
                probs.append('the stack %d B deep (at most %d)' % (
                    depth, S.STACK_2D))
            if not poison and r.ended() == 'stop':
                n, shown = M1.SR_stray(r, owners(b, r.loads))
                if n:
                    probs.append('%d stray writes: %s' % (n, shown[:3]))
                black = job.kind in ('open', 'close')
                probs += ['publish order: ' + x for x in
                          K.order(K.screen_stores(r.writes()), black)]
            return mj, fill, probs, compared, depth, x2n, x2drawn
        finally:
            shutil.rmtree(str(work), ignore_errors=True)
    work_list = [(mj, 0xA5, False) for mj in js] + \
        [(mj, 0x5A, True) for mj in js]
    out = {'jobs': len(js), 'runs': 0, 'compared': 0, 'kinds': {},
           'pages': {}, 'by_run': {}, 'problems': [], 'stack': 0,
           'excluded': {}, 'x2': {'bytes': 0, 'drawn_by_reference': 0}}
    for mj in all_jobs:
        if mj.job.excluded:
            out['excluded'][mj.job.excluded] = out['excluded'].get(
                mj.job.excluded, 0) + 1
    try:
        with ThreadPoolExecutor(jobs) as ex:
            for mj, fill, probs, compared, depth, x2n, x2d in ex.map(
                    one, work_list):
                out['runs'] += 1
                out['compared'] += compared
                out['stack'] = max(out['stack'], depth or 0)
                if fill == 0xA5:
                    k = mj.job.kind
                    out['kinds'][k] = out['kinds'].get(k, 0) + 1
                    pk = '%s %s' % (mj.page, k)
                    out['pages'][pk] = out['pages'].get(pk, 0) + 1
                    out['by_run'][mj.run] = out['by_run'].get(mj.run, 0) + 1
                    out['x2']['bytes'] += x2n
                    out['x2']['drawn_by_reference'] += x2d
                for pr in probs:
                    out['problems'].append('%s %s %s (%s) fill $%02X: %s' % (
                        mj.run, mj.job.kind, mj.job.name, mj.page, fill, pr))
    finally:
        shutil.rmtree(str(root), ignore_errors=True)
    return out


