def mine(mj: MJob) -> bool:
    return mj.page in ('load', 'save', 'key setup', 'display & sound',
                       'controls', 'benchmark')


def timing(b, setchg: Dict[str, int], jobs: int = 2,
           work_root: Path = OUT) -> Dict:
    """Each frame of this part's pages (runs A, K2, B; fill $A5, no write
    log) under each profile with --cost-timed: m_display alone in phase
    30, ms by page and kind (a frame redrawn whole or by the skull)."""
    import shutil
    import tempfile
    from concurrent.futures import ThreadPoolExecutor
    from native import s2run as SR
    js = [mj for run in ('a', 'k2', 'bench') for mj in jobs_of(run, setchg)
          if not mj.job.excluded and mine(mj)]
    root = Path(tempfile.mkdtemp(prefix='tmp-time-', dir=str(work_root)))

    def one(arg):
        mj, prof = arg
        work = root / ('%s-%s-%s' % (mj.run, mj.job.name, prof))
        try:
            recs, _ = job_records(b, mj.job, 0xA5, False)
            r = M1.run_calls(b, recs, [M1.call_of(mj.job)], 0xA5, work,
                             M1.SNAP, profile=prof)
            if r.ended() != 'stop':
                raise Menu2Error('%s: %s' % (mj.job.name, r.ended()))
            return mj, prof, SR.phase_ms(r, prof).get(30, 0.0)
        finally:
            shutil.rmtree(str(work), ignore_errors=True)
    out: Dict = {}
    try:
        with ThreadPoolExecutor(jobs) as ex:
            work_list = [(mj, p) for p in M1.PROFILES for mj in js]
            groups: Dict[Tuple[str, str], List[float]] = {}
            for mj, prof, ms in ex.map(one, work_list):
                groups.setdefault((prof, '%s %s' % (mj.page, mj.job.kind)),
                                  []).append(ms)
        for (prof, key), v in sorted(groups.items()):
            out.setdefault(prof, {})[key] = M1.stats(v)
    finally:
        shutil.rmtree(str(root), ignore_errors=True)
    return out


