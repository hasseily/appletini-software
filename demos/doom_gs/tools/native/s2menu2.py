BUDGET = 4000                   # s2menu2's (SCREENS.md 4.1, 7.3)
NAMES = 128 * 8                 # plk_names in this part's data


def sizes(obj: Path = OUT) -> Dict:
    """The image s2m2 (MENUW with both menu parts): s2layout's size table
    and its room; this part's module's code and data against its 4,000 B
    (the names, 1,024 B of the data, counted apart for 4.1's split; the
    sign's font, which this part's budget also held, went at wave 6's
    integration: S2MENU2-4)."""
    from native import s2run as SR
    b = SR.load_build(obj, 's2m2', 'MENUW')
    ms = SR.module_sizes(b)
    text = (obj / 's2m2.map').read_text()
    rows, problems = S.check_map('MENUW', text)
    segs = M1.module_segments(text).get('s2_menu2', {})
    code = segs.get('S2CODE', 0)
    data = sum(v for k, v in segs.items() if k != 'S2CODE')
    out = {'table': rows, 'problems': list(problems), 'code': code,
           'data': data, 'names': NAMES, 'own': code + data,
           'budget': BUDGET, 'glue': ms.modules.get('s2_menut', 0),
           's2menu1': sum(ms.modules.get(m, 0) for m in M1.OWN_MODULES),
           'extent': ['$%04X' % ms.extent[0], '$%04X' % (ms.extent[1] - 1)],
           'room_end': '$%04X' % M1.ROOM_END}
    out['total'] = code + data
    if code + data > BUDGET:
        out['problems'].append('s2_menu2 %d B, over its %d B'
                               % (code + data, BUDGET))
    if ms.extent[1] > M1.ROOM_END:
        out['problems'].append('MENUW ends at $%04X, past its room'
                               % (ms.extent[1] - 1))
    return out


def report(args, jobs: int = 2) -> Dict:
    from native import s2run as SR
    out: Dict = {}
    if not args.no_build:
        SR.make('s2menu2')
    if args.capture or not all((run_root(r) / 'index.json').exists()
                               for r in RUNS) or not M1.CALLS_FILE.exists():
        out['capture'] = capture()
    data = M1.load_calls()
    setchg = M1.settings_by_frame(data)
    b = SR.load_build(OUT, 's2m2t', 'MENUW')
    out['sizes'] = sizes()
    keys = ('sizes',)
    if args.check:
        out['frames'] = check_frames(b, setchg, jobs=jobs)
        out['chains'] = check_chains(b, setchg, data, jobs)
        # (s2menu1's engine on this image, its t_num as request S2MENU2-2
        # asks: every M_Responder and M_Ticker call of the call log)
        out['responders'] = M1.check_responders(b, data, 0xA5, jobs, OUT)
        out['tickers'] = M1.check_tickers(b, data, 0xA5, jobs, OUT)
        keys += ('frames', 'chains', 'responders', 'tickers')
    if args.timing:
        out['timing'] = timing(b, setchg, jobs)
    if args.planted:
        out['planted'] = planted(setchg, jobs)
    problems = sum(len(out[k]['problems']) for k in keys)
    if args.planted:
        problems += sum(1 for v in out['planted'].values() if not v['caught'])
    out['ok'] = problems == 0
    (OUT / 'report.json').write_text(json.dumps(out, indent=1) + '\n')
    return out


def summary(out: Dict) -> str:
    lines = ['s2menu2: %s' % ('ok' if out.get('ok') else 'PROBLEMS')]
    if 'capture' in out:
        lines.append('captured: %s' % json.dumps(out['capture']))
    sz = out.get('sizes')
    if sz:
        lines.append('sizes: s2_menu2 %d B (code %d, data %d with the names '
                     '%d): %d of %d B; s2menu1 %d B; glue %d B; MENUW '
                     '%s-%s; %s'
                     % (sz['own'], sz['code'], sz['data'], sz['names'],
                        sz['total'], sz['budget'], sz['s2menu1'], sz['glue'],
                        sz['extent'][0], sz['extent'][1],
                        '; '.join(sz['problems']) or 'within its room'))
    for key in ('frames', 'chains', 'responders', 'tickers'):
        r = out.get(key)
        if r is None:
            continue
        info = {k: v for k, v in r.items() if k != 'problems'}
        lines.append('%s: %s, %d problems' % (key, json.dumps(info),
                                               len(r['problems'])))
        lines += ['  ' + x for x in r['problems'][:10]]
    if 'timing' in out:
        lines.append('timing (ms): %s' % json.dumps(out['timing']))
    for name, v in out.get('planted', {}).items():
        lines.append('planted %s (%s): %s, %d jobs, %d problems, e.g. %s'
                     % (name, v['what'], 'caught' if v['caught']
                        else 'NOT CAUGHT', v['jobs'], v['problems'],
                        v['first'][:1]))
    return '\n'.join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--inc', type=Path)
    parser.add_argument('--capture', action='store_true',
                        help='the reference\'s runs K1, K2, B and the call '
                        'log again')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--timing', action='store_true')
    parser.add_argument('--planted', action='store_true')
    parser.add_argument('--all', action='store_true',
                        help='--capture --check --timing --planted')
    parser.add_argument('--no-build', action='store_true')
    parser.add_argument('--jobs', type=int, default=2)
    args = parser.parse_args(argv)
    try:
        if args.inc:
            M1.write_if_changed(args.inc, inc_text())
            return 0
        if args.all:
            args.capture = args.check = args.timing = args.planted = True
        if not (args.capture or args.check or args.timing or args.planted):
            parser.print_help()
            return 2
        out = report(args, args.jobs)
    except (Menu2Error, M1.MenuError) as error:
        print('s2menu2: %s' % error, file=sys.stderr)
        return 1
    print(summary(out))
    return 0 if out['ok'] else 1


