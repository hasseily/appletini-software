def planted(setchg: Dict[str, int], jobs: int = 2,
            only: Optional[Sequence[str]] = None) -> Dict:
    """Each planted bug in a scratch copy of s2_menu2.s, pl_keys.s or the
    generated plkeys.inc, built into a scratch directory, and the frames
    of its runs and pages checked (the first frame redrawn whole of each
    page, and every one of the key setup's)."""
    import shutil
    import tempfile
    from native import s2run as SR
    out = {}
    for pl in PLANTS:
        if only is not None and pl.name not in only:
            continue
        root = Path(tempfile.mkdtemp(prefix='tmp-plant-', dir=str(OUT)))
        try:
            src = root / 'src'
            src.mkdir()
            for f in ('s2_menu2.s', 'pl_keys.s'):
                shutil.copy(str(ROOT / 'src' / 'native' / f), str(src / f))
            build = root / 'build'
            variables = ['S2M2SRC=%s' % src, 'S2M2PLSRC=%s' % src,
                         'S2M2_DIR=%s' % build]
            if pl.source.startswith('gen/'):
                SR.make('s2menu2', variables=variables)
                path = build / pl.source
            else:
                path = src / pl.source
            text = path.read_text()
            n = text.count(pl.old)
            if n != 1 and not pl.source.startswith('gen/'):
                raise Menu2Error('%s: the planted text is not in %s once'
                                 % (pl.name, pl.source))
            if n == 0:
                raise Menu2Error('%s: the planted text is not in %s'
                                 % (pl.name, pl.source))
            path.write_text(text.replace(pl.old, pl.new))
            if pl.source.startswith('gen/'):
                # (make's times have a second's resolution here: the
                # objects built from the include a moment ago and the
                # images linked from them are removed from the scratch
                # build, so they are made again)
                for f in ('s2_menu2.o', 's2m2.map', 's2m2t.map'):
                    (build / f).unlink()
            SR.make('s2menu2', variables=variables)
            img = 's2m2t.img'
            if (build / img).read_bytes() == (OUT / img).read_bytes():
                raise Menu2Error('%s: the planted image is the tree\'s'
                                 % pl.name)
            b = SR.load_build(build, 's2m2t', 'MENUW')
            seen = set()

            def pick(mj: MJob) -> bool:
                if mj.run not in pl.runs or mj.page not in pl.pages:
                    return False
                if mj.page == 'key setup':
                    return mj.job.kind == 'full'
                key = (mj.run, mj.page)
                if mj.job.kind not in ('full', 'open') or key in seen:
                    return False
                seen.add(key)
                return True
            r = check_frames(b, setchg, pl.runs, jobs, root, pick=pick)
            out[pl.name] = {'what': pl.what, 'runs': list(pl.runs),
                            'jobs': r['jobs'],
                            'caught': bool(r['problems']) and r['jobs'] > 0,
                            'problems': len(r['problems']),
                            'first': r['problems'][:2]}
        finally:
            shutil.rmtree(str(root), ignore_errors=True)
    return out


