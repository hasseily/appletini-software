class Case(NamedTuple):
    op: str
    pokes: List[Tuple[int, bytes]]
    cont: bool = False          # goes on from the case before: same run


def encode(cases: Sequence[Case]) -> bytes:
    out = bytearray()
    for c in cases:
        pokes = []
        for at, data in c.pokes:
            for k in range(0, len(data), 255):
                pokes.append((at + k, data[k:k + 255]))
        if len(pokes) > 255:
            raise RunError('a case with %d pokes' % len(pokes))
        out += bytes([OPS[c.op], len(pokes)])
        for at, data in pokes:
            out += struct.pack('<HB', at, len(data)) + data
    out.append(END)
    return bytes(out)


# FM and the listener in the tic-side block (FM_X .. LS_ANGLE's end), then
# LS_ON and SND_SFXVOL after the mailboxes (s2layout SC_EXTRA, request
# FXCHAN-2 as integrated): an out record's s2t is the two runs joined
S2T_RUN = S.S2T['LS_ANGLE'] + 4 - S.S2T['FM_X']
S2T_TAIL = S2T_RUN + S.SC_EXTRA_SIZE


def extra_base(b: Build) -> int:
    return S.sc_extra_base(b.sc_base, b.channels)


def out_ranges(b: Build) -> List[Tuple[int, int]]:
    """The out records' ranges: the channel blocks; the scratch block;
    FM and the listener; LS_ON and SND_SFXVOL; the asks (FCD_POS)."""
    lab = b.labels
    s2t = b.s2t_base
    out = [(b.sc_base, b.channels * (S.CHAN_SIZE + S.MAIL_SIZE)),
           (lab['fxc_scr'], 32),
           (s2t + S.S2T['FM_X'], S2T_RUN),
           (extra_base(b), S.SC_EXTRA_SIZE),
           (lab['fcd_ntr'], 1 + 6 * TRACES)]
    if 'fcd_nask' in lab:
        out.append((lab['fcd_nask'], 1 + 2 * ASKS))
    return out


def record_size(b: Build) -> int:
    return sum(n for _, n in out_ranges(b))


def image_records(b: Build, cases: bytes, fill: int) -> bytes:
    lab = b.labels
    img = bytearray(b'A2VMIMG1')

    def rec(kind, bank, address, data):
        for k in range(0, len(data), 0x8000):
            chunk = data[k:k + 0x8000]
            img.extend(struct.pack('<BBHI', kind, bank, address + k,
                                   len(chunk)))
            img.extend(chunk)
    rec(0, 0, 0x0000, bytes([fill]) * 0xC000)       # main, poisoned
    rec(0, 0, 0x0000, bytes(0x100))                 # zero page 0
    rec(0, 0, 0x0300, bytes(0xF0))                  # the persistent globals
    rec(2, 0, 0xE000, bytes([fill]) * 0x2000)       # the card, poisoned
    rec(3, 0, 0xD000, bytes([fill]) * 0x1000)
    rec(3, 0, 0xD000, (MATH_TABLES / 'squares.bin').read_bytes())
    rec(3, 0, 0xD800, b.files['lc1'])
    rec(3, 0, 0xDC00, b.files['far'])
    rec(0, 0, MAIN[0], b.files['main'])
    rec(0, 0, WMATH[0], b.files['w'])
    if 'lc' in b.files:
        rec(2, 0, 0xE900, b.files['lc'])
    t = MT_TBANK
    rec(1, t, 0x2000, (MATH_TABLES / 'sinelo.bin').read_bytes())
    rec(1, t, 0x4000, (MATH_TABLES / 'sinehi.bin').read_bytes())
    for k in range(4):
        rec(1, t, 0x6000 + 0x900 * k,
            (MATH_TABLES / ('tanto%d.bin' % k)).read_bytes())
    rec(1, t, 0x8400, (MATH_TABLES / 'quartlo.bin').read_bytes())
    rec(1, t, 0x8C00, (MATH_TABLES / 'quarthi.bin').read_bytes())
    # the out ranges
    rng = out_ranges(b)
    rec(0, 0, lab['fcd_nout'], bytes([len(rng)]))
    rec(0, 0, lab['fcd_olo'], bytes(a & 0xFF for a, _ in rng))
    rec(0, 0, lab['fcd_ohi'], bytes(a >> 8 for a, _ in rng))
    rec(0, 0, lab['fcd_olen'], bytes(n for _, n in rng))
    rec(0, 0, lab['fcd_in'], cases)
    return bytes(img)


class Result(NamedTuple):
    records: List[bytes]        # each case's out record
    state: Dict
    cost_us: Optional[float]    # phase 30's time over the calls, us
    calls: int


def run_chunk(b: Build, cases: Sequence[Case], work: Path,
              profile: Optional[str] = None, fill: int = FILL) -> Result:
    lab = b.labels
    data = encode(cases)
    if len(data) > CASES[1] - CASES[0]:
        raise RunError('%d bytes of cases' % len(data))
    size = record_size(b)
    if size * len(cases) > OUTS[1] - OUTS[0]:
        raise RunError('%d out records do not fit' % len(cases))
    work.mkdir(parents=True, exist_ok=True)
    (work / 'fx.img').write_bytes(image_records(b, data, fill))
    (work / 'rom.bin').write_bytes(bytes(0x4000))
    last = OUTS[0] + max(1, size * len(cases)) - 1
    args = [str(A2VM), '--rom', str(work / 'rom.bin'), '--core', 'w65c02s',
            '--io-cycles', '0', '--image', str(work / 'fx.img'),
            '--switch', 'lc_read=1', '--switch', 'lc_write=1',
            '--switch', 'lc_bank2=0',
            '--reg', 'pc=%X' % lab['fcd_start'], '--reg', 'p=34',
            '--stop-pc', '%X' % lab['fcd_halt'],
            '--cycles', str(CYCLE_LIMIT),
            '--state', str(work / 'state.json'),
            '--snapshot-dir', str(work), '--final-snapshot',
            '--snapshot-ranges', 'main:%X-%X' % (OUTS[0], last)]
    report = work / 'cost.json'
    if profile:
        (work / 'cost.txt').write_text(costs.text(profile))
        args += ['--cost', str(work / 'cost.txt'), '--cost-timed',
                 '--cost-phase', '%X' % lab.get('PHASE', 0x0300),
                 '--cost-report', str(report)]
    try:
        r = bounded.run(args, timeout=RUN_TIMEOUT, max_bytes=MAX_FILE,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                        universal_newlines=True)
    except subprocess.TimeoutExpired:
        raise RunError('a2vm did not finish in %d s' % RUN_TIMEOUT)
    sp = work / 'state.json'
    if r.returncode or not sp.exists():
        raise RunError('a2vm failed: %s' % r.stdout[-2000:])
    state = json.loads(sp.read_text())
    if state.get('pc') != lab['fcd_halt']:
        raise RunError('a2vm stopped at $%04X (%s), not at fcd_halt' % (
            state.get('pc', -1), state.get('end')))
    snap = None
    for p in sorted(work.glob('*.img')):
        if p.name != 'fx.img':
            snap = p
    if snap is None:
        raise RunError('no snapshot')
    mem = _main_of(snap.read_bytes())
    out = bytes(mem[OUTS[0]:OUTS[0] + size * len(cases)])
    records = [out[k * size:(k + 1) * size] for k in range(len(cases))]
    cost = None
    if profile and report.exists():
        text = report.read_text()
        c = json.loads(text[text.rfind('{"final"'):])['cost']
        mhz = costs.parameters(profile)['fabric_mhz']
        phase = (S.PHASE_2D if hasattr(S, 'PHASE_2D') else 30)
        cost = c['phases'][phase] / mhz / max(1, len(cases))
    return Result(records, state, cost, len(cases))


def _main_of(data: bytes) -> bytearray:
    if data[:8] != b'A2VMIMG1':
        raise RunError('not an A2VMIMG1 snapshot')
    mem = bytearray(0x10000)
    at = 8
    while at < len(data):
        kind, bank, address, length = struct.unpack_from('<BBHI', data, at)
        at += 8
        if kind == 0:
            mem[address:address + length] = data[at:at + length]
        at += length
    return mem


def chunks(b: Build, cases: Sequence[Case]) -> List[List[Case]]:
    """The cases cut into runs that fit (a sequence is never cut: a case
    marked cont stays with the one before)."""
    size = record_size(b)
    cap_out = (OUTS[1] - OUTS[0]) // size
    cap_in = CASES[1] - CASES[0] - 1
    out: List[List[Case]] = []
    cur: List[Case] = []
    used = 0
    groups: List[List[Case]] = []
    for c in cases:
        if not c.cont or not groups:
            groups.append([c])
        else:
            groups[-1].append(c)
    for g in groups:
        n = len(encode(g)) - 1
        if cur and (used + n > cap_in or len(cur) + len(g) > cap_out):
            out.append(cur)
            cur, used = [], 0
        if n > cap_in or len(g) > cap_out:
            raise RunError('a sequence of %d cases does not fit a run'
                           % len(g))
        cur += g
        used += n
    if cur:
        out.append(cur)
    return out


def run(b: Build, cases: Sequence[Case], profile: Optional[str] = None,
        fill: int = FILL, jobs: int = 2) -> Tuple[List[bytes], List[float]]:
    """Every case's out record (in order) and the runs' us a call."""
    parts = chunks(b, cases)
    PART.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix='tmp-fxcrun-', dir=str(PART)))
    try:
        def one(k):
            return run_chunk(b, parts[k], temp / ('r%04d' % k), profile, fill)
        if jobs > 1 and len(parts) > 1:
            from concurrent.futures import ThreadPoolExecutor
            with ThreadPoolExecutor(max_workers=jobs) as ex:
                results = list(ex.map(one, range(len(parts))))
        else:
            results = [one(k) for k in range(len(parts))]
        for k in range(len(parts)):
            shutil.rmtree(str(temp / ('r%04d' % k)), ignore_errors=True)
    finally:
        shutil.rmtree(str(temp), ignore_errors=True)
    records = [r for res in results for r in res.records]
    costs_us = [res.cost_us for res in results if res.cost_us is not None]
    return records, costs_us


# ---------------------------------------------------------------------------
# The out record, decoded
# ---------------------------------------------------------------------------

class Out(NamedTuple):
    table: bytes                # the channel records
    mail: bytes                 # the mailboxes
    scratch: bytes
    s2t: bytes                  # FM_X .. LS_ANGLE, LS_ON, SND_SFXVOL
    trace: List[Tuple[int, int, int, int]]  # each adjust: c, aud, vol, sep
    asks: List[int]             # the handles s2t_pos was asked (FCD_POS)


def decode(b: Build, rec: bytes) -> Out:
    n = b.channels
    t = n * S.CHAN_SIZE
    at = n * (S.CHAN_SIZE + S.MAIL_SIZE)
    table, mail = rec[:t], rec[t:at]
    scratch = rec[at:at + 32]
    at += 32
    s2t = rec[at:at + S2T_TAIL]
    at += S2T_TAIL
    nt = rec[at]
    trace = []
    for i in range(min(nt, TRACES)):
        r = rec[at + 1 + 6 * i:at + 7 + 6 * i]
        trace.append((r[0], r[5], r[1] | r[2] << 8, r[3] | r[4] << 8))
    at += 1 + 6 * TRACES
    asks: List[int] = []
    if 'fcd_nask' in b.labels:
        na = rec[at]
        asks = [rec[at + 1 + 2 * i] | rec[at + 2 + 2 * i] << 8
                for i in range(min(na, ASKS))]
    return Out(table, mail, scratch, s2t, trace, asks)


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--cfg', type=Path)
    args = ap.parse_args(argv)
    if args.cfg:
        text = cfg_text()
        if not (args.cfg.exists() and args.cfg.read_text() == text):
            args.cfg.parent.mkdir(parents=True, exist_ok=True)
            args.cfg.write_text(text)
        return 0
    ap.print_help()
    return 1


if __name__ == '__main__':
    sys.exit(main())
