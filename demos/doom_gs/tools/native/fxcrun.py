def cfg_text() -> str:
    card = {name: (lo, hi) for name, lo, hi in S.S2_CARD}

    def area(name, lo, hi, file, extra=''):
        return '    %-7s start = $%04X, size = $%04X, %sfile = %s;\n' % (
            name + ':', lo, hi - lo, extra, file)
    out = ('# Generated by tools/native/fxcrun.py --cfg (part fxchan).\n'
           '# Do not edit.\nMEMORY {\n')
    out += area('SNDZP', S.ZP_MUSIC[0], S.ZP_FXRING[0], '""', 'type = rw, ')
    out += area('MAIN', MAIN[0], MAIN[1], '"%O.main"', 'fill = yes, ')
    out += area('CASES', CASES[0], CASES[1], '""', 'type = rw, ')
    out += area('W', WMATH[0], WMATH[1], '"%O.w"')
    out += area('OUTS', OUTS[0], OUTS[1], '""', 'type = rw, ')
    out += area('LC1', 0xD800, 0xDC00, '"%O.lc1"')
    out += area('FAR', 0xDC00, 0xE000, '"%O.far"')
    for key, name in (('RING', 'the song ring and its mirror'),
                      ('LIST', 'the player\'s write lists'),
                      ('STATE', 'the player\'s state')):
        out += area(key, card[name][0], card[name][1], '""', 'type = rw, ')
    r = card['S2\'s code and tables']
    out += area('SND', r[0], r[1], '"%O.lc"', 'fill = yes, ')
    out += area('FXC', S.FX_CODE[0], S.FX_CODE[1], '"%O.lc"', 'fill = yes, ')
    out += '}\nSEGMENTS {\n'
    rows = [('SNDZP', 'SNDZP', 'type = zp, optional = yes'),
            ('DRVCODE', 'MAIN', 'type = ro'),
            ('S2CODE', 'MAIN', 'type = ro, define = yes'),
            ('S2RODATA', 'MAIN', 'type = ro, define = yes'),
            ('DRVDATA', 'MAIN', 'type = rw'),
            ('CASES', 'CASES', 'type = bss, define = yes'),
            ('MATHRND', 'W', 'type = ro, align = $100'),
            ('MATHW', 'W', 'type = ro'),
            ('OUTS', 'OUTS', 'type = bss, define = yes'),
            ('MATHLC', 'LC1', 'type = ro'),
            ('MATHFAR', 'FAR', 'type = ro'),
            ('SNDRING', 'RING', 'type = bss, align = $100, optional = yes'),
            ('SNDLIST', 'LIST', 'type = bss, optional = yes'),
            ('SNDBSS', 'STATE', 'type = bss, optional = yes'),
            ('SNDCODE', 'SND', 'type = ro, optional = yes'),
            ('SNDRODATA', 'SND', 'type = ro, optional = yes'),
            ('FXCODE', 'FXC', 'type = ro, define = yes, optional = yes')]
    for name, load, extra in rows:
        out += '    %-10s load = %s, %s;\n' % (name + ':', load, extra)
    return out + '}\n'


