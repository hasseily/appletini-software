#!/usr/bin/env python3
"""a2vm runs of the channel logic (milestone 11, part fxchan;
docs/m11-parts/fxchan.md): the test machines of src/native/m11/fxchan.mk
under the driver src/native/fx_cdrv.s, many cases a run.

Usage:  python3 tools/native/fxcrun.py --cfg OUT      the ld65 map
        python3 tools/native/fxcrun.py --smoke         one case a build

The builds (fxchan.mk), each in build/native/m11/fxchan/<name>.*:

    fxc8    FXCH8: 8 channels (s2-fxch8.inc), isPlaying injected
            (fx_cdrv -D FCD_PLAY) and the positions from a table
            (-D FCD_POS): comparisons 1-3 of docs/SCREENS.md 3
    fxc8r   FXCH8 with fxplay's fx_isplaying (fx.s's card part
            assembled for FXCH8): comparison 4, the two-tic case
    fxc3    3 channels (s2.inc, the release's places), fxplay's
            fx_isplaying: against tools/sound/fxchan.py
    fxcm8   MENUW's object (-D FXC_NOSEP) with fx_pcache's s2t_pos,
            FXCH8, isPlaying injected: the paused frame

The machine (a2vm's W65C02S, the RTL's core): main $0800-$17FF the driver,
the channel logic and their data; $1DBE-$1DBF gamemap (llayout's
G_GAMEMAP); $2000-$5FFF the cases; $6000-$6FFF
the math's W part (the game's math.s, not the render subset); $7000-$BFFF
the out records; the card's bank 1 the quarter squares, MATHLC, MATHFAR;
the card's $E000 part the channel blocks of the build's s2.inc, and with
fx_isplaying S2's player and fx.s's card part at the game's places; the
math tables in RamWorks bank 120. Every byte the cases do not set is the
fill ($A5 by default).

A run is bounded: cycles, wall time, file sizes (bounded.run); its
directory is the caller's or a tempfile directory, deleted.
"""

