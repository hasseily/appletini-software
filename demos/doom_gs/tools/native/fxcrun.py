def make(part: Optional[Path] = None, source: Path = SOURCE,
         fxsrc: Optional[Path] = None) -> List[str]:
    """make -f m11.mk part P=fxchan into `part` (build/native/m11/fxchan),
    fx_chan.s, fx_pcache.s, fx_cdrv.s from `source` and fx.s from `fxsrc`
    (scratch copies for the planted bugs); fails on a warning or when
    s2layout.py's check fails (the shared includes are always remade)."""
    part = part or PART
    args = ['make', '-s', '-C', str(SOURCE), '-f', 'm11.mk', 'part',
            'P=fxchan', 'ROOT=%s' % ROOT, 'FXCHAN_DIR=%s' % part,
            'FXCSRC=%s' % source]
    if fxsrc is not None:
        args.append('FXSRC=%s' % fxsrc)
    notes: List[str] = []

    def go(extra):
        return bounded.run(args + extra, timeout=300, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, universal_newlines=True)
    result = go([])
    if result.returncode:
        raise RunError('the build failed:\n' + result.stdout[-3000:])
    if 'arning' in result.stdout:
        raise RunError('the build warns:\n' + result.stdout[-3000:])
    return notes


def use_part(part: Path) -> None:
    """Runs and loads from another build directory (a planted bug's)."""
    global PART
    PART = Path(part)


def read_labels(path: Path) -> Dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[0] == 'al':
            out[parts[2].lstrip('.')] = int(parts[1], 16)
    return out


class Build(NamedTuple):
    name: str
    dir: Path
    labels: Dict[str, int]
    sc_base: int
    channels: int
    s2t_base: int
    files: Dict[str, bytes]


def load(name: str, part: Optional[Path] = None) -> Build:
    d = part or PART
    labels = read_labels(d / (name + '.lbl'))
    b = S.BUILDS[BUILDS[name]['inc']]
    files = {}
    for suffix in ('main', 'w', 'lc1', 'far', 'lc'):
        p = d / ('%s.%s' % (name, suffix))
        if p.exists():
            files[suffix] = p.read_bytes()
    return Build(name, d, labels, b.sc_base, b.channels, b.s2t_base, files)


def have(name: str, part: Optional[Path] = None) -> Optional[str]:
    """None when the build and the tools exist, else what is missing."""
    part = part or PART
    for p in (part / (name + '.lbl'), part / (name + '.main'), A2VM,
              MATH_TABLES / 'tanto0.bin', MATH_TABLES / 'squares.bin'):
        if not p.exists():
            return '%s is missing' % p
    return None


