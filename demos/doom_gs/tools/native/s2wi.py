def picnum() -> int:
    """The release's lump number of WIMAP0 (upstream's picturenum of the
    intermission's picture, PALST's PS_PICTURE)."""
    from native import umodel as U
    return U.Release().index('WIMAP0')


def inc_text() -> str:
    return ('; Generated by tools/native/s2wi.py (part s2wi, docs/m11-parts/'
            's2wi.md). Do not edit.\n\n'
            '; WIMAP0\'s lump number in the release (upstream\'s picturenum, '
            'PALST\'s PS_PICTURE)\n'
            'WI_PICNUM       = $%04X\n' % picnum())


def write_inc(path: Path) -> None:
    text = inc_text()
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    tmp = path.with_name(path.name + '.tmp')
    tmp.write_text(text)
    tmp.replace(path)


def inc_values(path: Path) -> Dict[str, int]:
    out = {}
    for line in path.read_text().splitlines():
        f = line.split(';')[0].split('=')
        if len(f) == 2 and f[1].strip().startswith('$'):
            out[f[0].strip()] = int(f[1].strip()[1:], 16)
    return out


