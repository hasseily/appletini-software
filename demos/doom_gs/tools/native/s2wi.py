class Job(NamedTuple):
    tag: str
    cases: Tuple[Case, ...]
    fill: int
    poison: bool
    chained: bool
    first_state: Optional[bytes]    # a chain's continuation: SS_PALST,
    #                                 SS_WIW, S2NIB as the last run left


def expected(c: Case) -> Dict[str, Any]:
    from native import s2cap as C, s2state as ST
    pdf = c.case.one('PDF')
    sym = C.sym
    lumps = c.case.before.get(sym('wi_stuff65.s:lumps'), 2 * NLUMPS)
    words = [lumps[k] | lumps[k + 1] << 8 for k in range(0, 2 * NLUMPS, 2)]
    handles, ok = ST.gfx_encode(words)
    return {'screen': c.case.screen_after,
            'snl': C.val(pdf, 'wi_stuff65.s:snl_pointeron'),
            'scb': pdf.get(sym('i_viigs65.s:scb'), 200),
            'palette': pdf.get(sym('i_viigs65.s:palette'), 512),
            'picture': C.val(pdf, 'i_viigs65.s:picturenum'),
            'lumps': handles if ok else None}


def run_job(job: Job, b, profile: Optional[str], work_root: Path,
            gen: Dict[str, int]) -> Dict[str, Any]:
    from native import llayout as LL, s2check as K, s2run as SR
    if not 0 < len(job.cases) <= MAX_CASES:
        raise WiError('%s: %d cases' % (job.tag, len(job.cases)))
    stages = []
    for i, c in enumerate(job.cases):
        flags = F_LEFT if c.left else 0
        state = None
        if job.chained:
            if i == 0:
                flags |= F_INIT if job.first_state is None else 0
                state = job.first_state
            else:
                flags |= F_CHAINED
        stages.append(stage(c, job.fill, job.poison, flags, state))
    tints = {st.tintpal for st in stages}
    if len(tints) != 1:
        raise WiError('%s: the cases have %d TINTPALs' % (job.tag,
                                                         len(tints)))
    recs = store_records() + stage_records(stages) + card_records(gen) + \
        [(1, S.S2PAL, S.S2PAL_AT['S2P_TINTPAL'], stages[0].tintpal)]
    # the input as the boot leaves it (pl_init; S2WI-3): pl_poll runs first
    # in every frame
    from native import plinput as PI
    recs += PI.boot_records()
    if job.first_state is not None:     # a chain goes on: the native
        recs.append((1, S.S2PAL, S.S2PAL_AT['S2P_NIB'],    # tables
                     job.first_state[S.PALST_SIZE + 256:]))
    elif not any(c.black for c in job.cases):
        # the nibble tables at the frames' start: the picture's on the
        # screen (WIMAP0's, built by its first frame; s2pal's model of
        # buildNibtab, checked against ref816's NIBTAB by part s2pal). A
        # run with a new picture starts with none: its frame builds them.
        recs.append((1, S.S2PAL, S.S2PAL_AT['S2P_NIB'], picture_nibtab()))
    calls = [SR.Call('wit_case', k) for k in range(len(stages))]
    mb_lo, mb_hi = LL.G['G_WMINFO'], LL.G['WI_SNLPTR'] + 2
    snap = 'aux0:2000-9FFF,main:%04X-%04X,main:BC00-BFFF,%s' % (
        mb_lo, mb_hi - 1, STATE_SNAP)
    work = Path(tempfile.mkdtemp(prefix='tmp-run-', dir=str(work_root)))
    problems: List[str] = []
    try:
        r = SR.run(b, calls, job.fill, work, extra_records=recs,
                   write_log=False, snap_ranges=snap, profile=profile,
                   timeout=600.0, extra_args=[
                       '--write-log', write_log_ranges(b),
                       '--write-log-file', str(work / 'writes.log'),
                       '--write-log-limit', str(SR.WRITE_LOG_LIMIT)])
        if r.ended() != 'stop' or r.status() != S.S2S['DONE']:
            st = r.status()
            return {'tag': job.tag, 'cases': len(job.cases), 'problems': [
                '%s: the run ended %s, status %s' % (
                    job.tag, r.ended(), 'none' if st is None else
                    '$%02X' % st)], 'frame_ms': [], 'state': None,
                'stray': 0, 'stack': None, 'writes': 0}
        snaps = r.calls()
        writes = r.writes()
        n_stray, stray_list = SR.stray(writes, owners(b, r.loads, gen))
        sps = spans(b, writes)
        stack = SR.stack_depth(r)
    finally:
        shutil.rmtree(str(work), ignore_errors=True)
    if n_stray:
        problems.append('%s: %d stray writes: %s' % (job.tag, n_stray,
                                                    stray_list[:3]))
    if len(snaps) != len(job.cases) or len(sps) != len(job.cases):
        raise WiError('%s: %d snapshots, %d frames for %d cases' % (
            job.tag, len(snaps), len(sps), len(job.cases)))
    region = screen_region()
    frame_ms = []
    last_state = None
    for c, st, m, sp in zip(job.cases, stages, snaps, sps):
        tag = '%s (fill %02X%s%s)' % (c.name, job.fill,
                                      ', poisoned' if job.poison else '',
                                      ', chained' if job.chained else '')
        want = expected(c)
        got = bytes(m.storage('aux', 0)[S.SHR:S.SCREEN_END])
        res = K.compare(want['screen'], st.before, got, region)
        for a, v, ref in res.differ[:1]:
            row = (a - S.SHR) // S.ROW_BYTES if a < S.SCB else None
            problems.append('%s: %s $%04X: $%02X, ref $%02X%s' % (
                tag, 'row %d byte %d,' % (row, (a - S.SHR) % S.ROW_BYTES)
                if row is not None else 'colours', a, v, ref,
                ' (%d bytes differ)' % len(res.differ)
                if len(res.differ) > 1 else ''))
        for a, v, was in res.outside[:1]:
            problems.append('%s: $%04X changed outside the region: $%02X, '
                            'was $%02X' % (tag, a, v, was))
        snl = m.main[LL.G['WI_SNLPTR']] | m.main[LL.G['WI_SNLPTR'] + 1] << 8
        if snl != want['snl']:
            problems.append('%s: WI_SNLPTR %d, ref %d' % (tag, snl,
                                                         want['snl']))
        w = S.PALST_W
        pp = S.palst_places()
        if bytes(m.main[w + pp['PS_SCB']:w + pp['PS_SCB'] + 200]) != \
                want['scb']:
            problems.append('%s: PALST scb differs' % tag)
        if bytes(m.main[w + pp['PS_PALETTE']:w + pp['PS_PALETTE'] + 512]) \
                != want['palette']:
            problems.append('%s: PALST palette differs' % tag)
        pic = m.main[w + pp['PS_PICTURE']] | \
            m.main[w + pp['PS_PICTURE'] + 1] << 8
        if pic != want['picture']:
            problems.append('%s: picturenum $%04X, ref $%04X' % (
                tag, pic, want['picture']))
        if job.chained:
            lumps = bytes(m.main[S.PALST_W + S.PALST_SIZE:
                                 S.PALST_W + S.PALST_SIZE + NLUMPS])
            if want['lumps'] is None or lumps != want['lumps']:
                problems.append('%s: W_LUMPS %s, ref %s' % (
                    tag, lumps.hex(), want['lumps'].hex()
                    if want['lumps'] else 'unfit'))
        problems += ['%s: order: %s' % (tag, x)
                     for x in K.order(sp.stores, c.black)]
        if profile:
            kind = 'new picture' if c.black else (
                'stats' if c.state == 0 else 'next location')
            frame_ms.append((kind, ms(profile, sp.end - sp.start)))
        aux = m.storage('aux', S.S2STATE)
        nib = m.storage('aux', S.S2PAL)
        last_state = bytes(aux[S.SS['SS_PALST']:S.SS['SS_PALST'] +
                               S.PALST_SIZE]) + \
            bytes(aux[S.SS['SS_WIW']:S.SS['SS_WIW'] + 256]) + \
            bytes(nib[S.S2PAL_AT['S2P_NIB']:S.S2PAL_AT['S2P_NIB'] +
                      S.S2PAL_SIZE['S2P_NIB']])
    return {'tag': job.tag, 'cases': len(job.cases), 'problems': problems,
            'frame_ms': frame_ms, 'state': last_state, 'stray': n_stray,
            'stack': stack, 'writes': len(writes)}


def jobs_of(cs: Sequence[Case], modes: Sequence[str]
            ) -> Tuple[List[Job], List[List[Job]]]:
    """The injected jobs (independent) and the chains (each a list of
    jobs run in order, the next starting from the last's native state)."""
    inj: List[Job] = []
    if 'injected' in modes:
        for fill, poison in FILLS:
            groups: Dict[Tuple[bytes, bool], List[Case]] = {}
            for c in cs:     # (a new picture's frames apart: no tables)
                groups.setdefault((c.case.carried('TINTPAL'), c.black),
                                  []).append(c)
            for g in groups.values():
                for i in range(0, len(g), MAX_CASES):
                    part = tuple(g[i:i + MAX_CASES])
                    inj.append(Job('injected %02X %s..%s' % (
                        fill, part[0].name, part[-1].name), part, fill,
                        poison, False, None))
    chains: List[List[Job]] = []
    if 'chained' in modes:
        by: Dict[int, List[Case]] = {}
        for c in cs:
            by.setdefault(c.inter, []).append(c)
        for n, g in sorted(by.items()):
            chain = []
            for i in range(0, len(g), MAX_CASES):
                part = tuple(g[i:i + MAX_CASES])
                chain.append(Job('chained %d (%s..%s)' % (
                    n, part[0].name, part[-1].name), part, 0xA5, False, True,
                    None))
            chains.append(chain)
    return inj, chains


def gen_values(obj: Path) -> Dict[str, int]:
    del obj
    return inc_values(SHARED_GEN / 's2.inc')


def check(profile: Optional[str] = None, obj: Path = OUT, jobs: int = JOBS,
          modes: Sequence[str] = ('injected', 'chained')
          ) -> Dict[str, Any]:
    b = build_of(obj)
    gen = gen_values(obj)
    cs, excluded = cases()
    if not cs:
        raise WiError('no intermission frame in the %s capture' % RUN)
    inj, chains = jobs_of(cs, modes)
    work_root = Path(tempfile.mkdtemp(prefix='tmp-s2wi-run-', dir=str(obj)))
    results: List[Dict[str, Any]] = []

    def chain_run(chain: List[Job]) -> List[Dict[str, Any]]:
        out, state = [], None
        for i, job in enumerate(chain):
            if i:
                job = job._replace(first_state=state)
            res = run_job(job, b, None, work_root, gen)
            out.append(res)
            state = res['state']
            if state is None:
                break
        return out
    try:
        with ThreadPoolExecutor(max(1, min(jobs, 4))) as ex:
            futs = [ex.submit(run_job, j, b, profile if j.fill == 0xA5
                              else None, work_root, gen) for j in inj]
            cfuts = [ex.submit(chain_run, ch) for ch in chains]
            results = [f.result() for f in futs]
            for f in cfuts:
                results += f.result()
    finally:
        shutil.rmtree(str(work_root), ignore_errors=True)
    problems = [p for r in results for p in r['problems']]
    kinds = {'stats': 0, 'next location': 0, 'new picture': 0}
    for c in cs:
        kinds['new picture' if c.black else (
            'stats' if c.state == 0 else 'next location')] += 1
    return {
        'run': RUN, 'cases': len(cs), 'excluded': excluded,
        'intermissions': len({c.inter for c in cs}), 'kinds': kinds,
        'pointer frames': sum(1 for c in cs if c.state != 0 and
                              expected(c)['snl']),
        'runs': [{k: v for k, v in r.items() if k not in ('state',
                                                          'frame_ms')}
                 for r in results],
        'frame_ms': [x for r in results for x in r['frame_ms']],
        'stray': sum(r['stray'] for r in results),
        'stack': max((r['stack'] or 0) for r in results),
        'problems': problems, 'profile': profile, 'modes': list(modes)}


# ---------------------------------------------------------------------------
# The nibble tables' units a patch needs (s2_wi.s: 16 in the slots)
# ---------------------------------------------------------------------------

def unit_needs() -> Dict[str, Any]:
    """For every patch WI_Drawer can draw, at each row it can be drawn at
    (the titles, the counts, the times, the splats and the pointer at the
    nine nodes), the most units of 2 pages (a palette and a parity) its
    rows need within one band of 40 rows on WIMAP0."""
    from native import s2pal as P
    lp = P.lumps()
    rel = lp.rel
    scb = [x & 15 for x in lp.get(rel.index('WIMAP0'))[32000:32200]]

    def head(n):
        return struct.unpack('<hhhh', lp.get(rel.index(n))[:8])

    def units(top: int, h: int) -> int:
        best = 0
        for b0 in range(0, 200, 40):
            rows = range(max(top, b0, 0), min(top + h, b0 + 40, 200))
            best = max(best, len({(scb[r], r & 1) for r in rows}))
        return best
    nodes = [(185, 164), (148, 143), (69, 122), (209, 102), (116, 89),
             (166, 55), (71, 56), (135, 29), (71, 24)]
    tops: List[Tuple[str, int]] = []
    for n in ['WILV%02d' % i for i in range(9)] + ['WIENTER', 'WIF']:
        _, h, _, t = head(n)
        tops += [(n, 2 - t), (n, 2 + 5 * head('WILV00')[1] // 4 - t)]
    for n, y in [('WIOSTK', 50), ('WIOSTI', 68), ('WISCRT2', 86)] + [
            (n, y) for n in ['WIPCNT'] + ['WINUM%d' % i for i in range(10)]
            for y in (50, 68, 86)] + [
            (n, y) for n in ['WITIME', 'WIPAR', 'WICOLON', 'WISUCKS'] +
            ['WINUM%d' % i for i in range(10)] for y in (160,)] + [
            (n, y) for n in ['WIMSTT', 'WICOLON', 'WISUCKS'] +
            ['WINUM%d' % i for i in range(10)] for y in (180,)]:
        tops.append((n, y - head(n)[3]))
    for _, y in nodes:
        tops.append(('WISPLAT', y - head('WISPLAT')[3]))
        tops.append(('WIURH0', max(y, 45) - head('WIURH0')[3]))
    worst = max(((units(t, head(n)[1]), n, t) for n, t in tops))
    return {'positions': len(tops), 'most': worst[0],
            'at': '%s rows %d-%d' % (worst[1], worst[2],
                                     worst[2] + head(worst[1])[1] - 1),
            'slots': 16}


