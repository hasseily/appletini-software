def sizes(obj: Path = OUT) -> Dict[str, Any]:
    """WIW (wiw: the image without the test glue) against its room and
    the size table; s2_wi's segments against the part's budget."""
    text = (obj / 'wiw.map').read_text()
    ms_ = S.read_map(text)
    part = text.split('Modules list:', 1)[1].split('Segment list:', 1)[0]
    segs: Dict[str, int] = {}
    mod = None
    for line in part.splitlines():
        if line and not line.startswith(' ') and line.rstrip().endswith(':'):
            mod = Path(line.strip()[:-1].split('(')[0]).stem
            continue
        f = line.split()
        if mod == 's2_wi' and f:
            segs[f[0]] = int(f[2][5:], 16)
    return {'modules': dict(ms_.modules), 's2_wi': segs,
            'code': segs.get('S2CODE', 0), 'code_budget': 1400,
            'data': segs.get('S2RODATA', 0) + segs.get('S2DATA', 0),
            'data_budget': 400,
            'table': (obj / 'wiw.sizes').read_text().splitlines()}


def stats(values: Sequence[float]) -> Dict[str, float]:
    v = sorted(values)
    if not v:
        return {}
    return {'n': len(v), 'median': round(v[len(v) // 2], 3),
            'p99': round(v[min(len(v) - 1, (99 * len(v)) // 100)], 3),
            'worst': round(v[-1], 3)}


def timing(res: Dict[str, Any]) -> Dict[str, Any]:
    by: Dict[str, List[float]] = {}
    for kind, v in res['frame_ms']:
        by.setdefault(kind, []).append(v)
        by.setdefault('all', []).append(v)
    return {k: stats(v) for k, v in sorted(by.items())}


def report(jobs: int = JOBS) -> Dict[str, Any]:
    t0 = time.time()
    out: Dict[str, Any] = {'part': 's2wi', 'checks': {}, 'timing': {}}
    for profile in PROFILES:
        res = check(profile, OUT, jobs,
                    ('injected', 'chained') if profile == 'f121'
                    else ('injected',))
        out['checks'][profile] = {k: v for k, v in res.items()
                                  if k != 'frame_ms'}
        out['timing'][profile] = timing(res)
    sz = sizes()
    out['sizes'] = sz
    stored = sum(n for m, n in sz['modules'].items()
                 if S.module_row(m) != 'MATHW')
    out['load_ms'] = round(stored * LOAD_US / 1000.0, 2)
    out['drain_ms'] = round((32000 + 512) * DRAIN_US / 1000.0, 2)
    out['units'] = unit_needs()
    out['planted'] = planted(jobs)
    problems = [p for c in out['checks'].values() for p in c['problems']]
    problems += ['planted bug not caught: %s' % p['bug']
                 for p in out['planted'] if not p['caught']]
    if sz['code'] > 0 and any('room' in line and 'OVER' in line
                              for line in sz['table']):
        problems.append('WIW is over its room')
    out['problems'] = problems
    out['ok'] = not problems
    out['seconds'] = round(time.time() - t0, 1)
    (OUT / 'report.json').write_text(json.dumps(out, indent=1) + '\n')
    return out


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--inc', type=Path)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--planted', action='store_true')
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--units', action='store_true')
    ap.add_argument('--profile', choices=PROFILES)
    ap.add_argument('--mode', choices=('injected', 'chained'))
    ap.add_argument('--jobs', type=int, default=JOBS)
    args = ap.parse_args(argv)
    if args.inc:
        write_inc(args.inc)
        return 0
    if args.units:
        print(json.dumps(unit_needs(), indent=1))
        return 0
    if args.check:
        res = check(args.profile, OUT, args.jobs,
                    (args.mode,) if args.mode else ('injected', 'chained'))
        print('%d cases (%s), %d runs, %d stray, stack %d B; excluded %d' %
              (res['cases'], res['kinds'], len(res['runs']), res['stray'],
               res['stack'], len(res['excluded'])))
        if args.profile:
            print(json.dumps(timing(res)))
        for p in res['problems'][:30]:
            print('  ' + p)
        print('%d problems' % len(res['problems']))
        return 1 if res['problems'] else 0
    if args.planted:
        bad = 0
        for p in planted(args.jobs):
            print('%-70s %s' % (p['bug'], 'caught (%d): %s' % (
                p['failures'], p['first']) if p['caught'] else 'NOT CAUGHT'))
            bad += not p['caught']
        return 1 if bad else 0
    if args.all:
        out = report(args.jobs)
        print(json.dumps({k: out[k] for k in ('timing', 'units', 'planted',
                                              'load_ms', 'drain_ms', 'ok')},
                         indent=1))
        for p in out['problems'][:30]:
            print('  ' + p)
        return 0 if out['ok'] else 1
    ap.print_help()
    return 2


if __name__ == '__main__':
    sys.exit(main())
