def write_log_ranges(b) -> str:
    """Every CPU write but: the stack page, the far layer's arguments and
    the drawers' zero page ($00-$05, $48-$7F), the image's code (its loops
    patch their operands) and WIW's runtime W ($8000-$BBFF: the band, the
    marks, the slots, the fetch buffer), the pixel rows 1-198 (32 KB a
    case: the whole screen is compared on the snapshots; rows 0 and 199,
    the frame's first and last band stores, stay for the order)."""
    lo, hi = b.segments['S2DATA']
    return ('main:0006-0047,main:0080-00FF,main:0200-65FF,main:%04X-%04X,'
            'main:BC00-FFFF,lc,lc1,aux0:0000-209F,aux0:9C60-FFFF,aux1-127,'
            'cpu:C000-C0FF' % (lo, hi))


class Span(NamedTuple):
    start: int
    end: int
    stores: List[Any]           # the screen stores (s2check.Store)
    published: int              # bytes s2_publish stored (rows 0, 199)


def spans(b, writes) -> List[Span]:
    """Each wi_frame of the glue: PHASE written PHV_2D, then 0."""
    from native import rlayout as R, s2check as K
    pcs = module_pcs(b)
    glue = pcs['s2_wit']
    pub = pcs['s2_pub']
    out: List[Span] = []
    cur: Optional[List[Any]] = None
    start = 0
    for w in writes:
        if w.storage == 'main' and w.offset == R.PHASE and \
                glue[0] <= w.pc <= glue[1]:
            if w.new == 2 * S.PHASE_2D:
                cur, start = [], w.clock
            elif w.new == 0 and cur is not None:
                st = K.screen_stores(cur)
                out.append(Span(start, w.clock, st, sum(
                    1 for x in cur if pub[0] <= x.pc <= pub[1])))
                cur = None
            continue
        if cur is not None:
            cur.append(w)
    return out


def ms(profile: str, clocks: int) -> float:
    from a2vm import costs
    return clocks / (costs.parameters(profile)['fabric_mhz'] * 1000.0)


