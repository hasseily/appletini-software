class Case(NamedTuple):
    name: str
    k: int                      # its index among the run's frames
    case: Any                   # s2cap.Case
    left: bool                  # display's I_SetPalette(0): a level left
    state: int                  # WI state at the start (0 stats, 1, -1)
    black: bool                 # a new picture: the black step
    inter: int                  # which intermission (0-7)


def cases(run: str = RUN) -> Tuple[List[Case], List[str]]:
    """The run's intermission frames, and the frames excluded (named)."""
    from native import s2cap as C
    rc = C.RunCases(C.run_dir(run))
    out: List[Case] = []
    excluded: List[str] = []
    inter = -1
    for k, (e, c) in enumerate(rc.frames()):
        b = c.before
        if b.point != 'PD0:display' or \
                C.val(b, 'g_game65.s:_g_gamestate') != GS_INTERMISSION:
            continue
        name = '%s/f%06d' % (run, e['frame'])
        pdf = c.one('PDF')
        if pdf is None:
            excluded.append('%s: no I_FinishUpdate' % name)
            continue
        if C.val(b, 'm_menu65.s:_g_menuactive'):
            excluded.append('%s: a menu over the intermission (s2menu1)'
                            % name)
            continue
        left = C.val(b, 'd_main65.s:oldgamestate') == GS_LEVEL
        if left:
            inter += 1
        st = C.val(b, 'wi_stuff65.s:state')
        out.append(Case(name, k, c, left, st - 0x10000 if st & 0x8000
                        else st,
                        bool(C.val(pdf, 'i_viigs65.s:palettecount')),
                        max(inter, 0)))
    return out, excluded


def screen_region() -> S.Region:
    wi, col = S.REGIONS['wi'], S.REGIONS['colors']
    return S.Region('intermission', 's2wi', wi.rows, col.scbs, col.palettes)


class Stage(NamedTuple):
    rec: bytes                  # the case's REC bytes
    before: bytes               # aux 0 $2000-$9FFF when wi_frame starts
    tintpal: bytes


def stage(c: Case, fill: int, poison: bool, flags: int,
          state: Optional[bytes] = None) -> Stage:
    """A case's stage record; `state`: the PALST and own block to use
    instead of the case's (a chain's continuation: SS_PALST's 768 then
    SS_WIW's 256)."""
    from native import llayout as LL, s2state as ST
    inj = ST.inject(c.case, 'intermission', fill, with_screen=False)
    pal = ST.inject(c.case, 'palettes', fill, with_screen=False)
    for i in (inj, pal):
        if i.unfit:
            raise WiError('%s: unfit %s' % (c.name, i.unfit))
    mb_lo, mb_hi = LL.G['G_WMINFO'], LL.G['WI_SNLPTR'] + 2
    main = bytearray([fill]) * (mb_hi - mb_lo)
    palst = bytearray([fill]) * S.PALST_SIZE
    own = bytearray([fill]) * 256
    gamma = None
    ss_pal, ss_own = S.SS['SS_PALST'], S.SS['SS_WIW']
    for kind, bank, address, data in inj.records + pal.records:
        for k, v in enumerate(data):
            a = address + k
            if kind == ST.MAIN and mb_lo <= a < mb_hi:
                main[a - mb_lo] = v
            elif kind == ST.AUX and bank == S.S2STATE:
                if ss_pal <= a < ss_pal + S.PALST_SIZE:
                    palst[a - ss_pal] = v
                elif ss_own <= a < ss_own + 256:
                    own[a - ss_own] = v
    for p in pal.places:
        if p.ref.endswith('_g_gamma'):
            gamma = p.value
    if gamma is None:
        raise WiError('%s: no gamma' % c.name)
    # PS_BEGUN (no upstream counterpart): s2_finish leaves it 0, so it is
    # 0 at every frame's start (SCREENS.md 1.3; s2_pub.s)
    palst[S.palst_places()['PS_BEGUN']] = 0
    if state is not None:
        palst[:] = state[:S.PALST_SIZE]
        own[:] = state[S.PALST_SIZE:S.PALST_SIZE + 256]
    screen, _ = ST.screen_image(c.case, fill, poison)
    rec = bytearray(REC)
    rec[REC_MAIN:REC_MAIN + len(main)] = main
    rec[REC_PALST:REC_PALST + S.PALST_SIZE] = palst
    rec[REC_OWN:REC_OWN + 256] = own
    tail = screen[S.SCB - S.SHR:]
    rec[REC_SCREEN:REC_SCREEN + len(tail)] = tail
    rec[REC_CTL:REC_CTL + 4] = bytes([flags, fill, gamma & 0xFF,
                                      gamma >> 8 & 0xFF])
    before = bytes([fill]) * (S.SCB - S.SHR) + tail
    return Stage(bytes(rec), before, c.case.carried('TINTPAL'))


_NIBTAB: Optional[bytes] = None


def picture_nibtab() -> bytes:
    """WIMAP0's 16 nibble tables (S2NIB) as drawPicture builds them."""
    global _NIBTAB
    if _NIBTAB is None:
        from native import s2pal as P, s2palmodel as M
        lp = P.lumps()
        pic = lp.get(lp.num('WIMAP0'))
        _NIBTAB = b''.join(M.build_nibtab(pic[M.PICTURE_PAIRS + 256 * i:
                                              M.PICTURE_PAIRS + 256 * i +
                                              256]) for i in range(16))
    return _NIBTAB


def stage_records(stages: Sequence[Stage]) -> List[Tuple[int, int, int,
                                                         bytes]]:
    banks: Dict[int, bytearray] = {}
    for k, st in enumerate(stages):
        bank, j = divmod(k, PER_BANK)
        data = banks.setdefault(T_STAGE + bank, bytearray(0xC000 - 0x0200))
        data[j * REC:(j + 1) * REC] = st.rec
    return [(1, b, 0x0200, bytes(d)) for b, d in sorted(banks.items())]


