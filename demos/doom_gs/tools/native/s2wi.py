#!/usr/bin/env python3
"""Part s2wi's checks (docs/SCREENS.md 1.5.5, 6, 7.3; docs/m11-parts/
s2wi.md): the intermission's image WIW against upstream's frames.

The truth is part s2cap's capture of the tour (build/native/m11/cases/
tour): every frame whose game state is the intermission (`_g_gamestate`
1 at its start), both states (the stats, the next location with its
pointer), each with display's state at its start (PD0: the wi counters,
`_g_wminfo`, WI_Init's lumps, the palette state, the screen), the palette
state at I_FinishUpdate's entry (PDF) and the screen after the frame.

The native side is the test image s2wt (src/native/s2_wit.s, the glue;
src/native/s2_wi.s, the image's code; the shared drawers, the publish, the
palettes, the effect service and part plinput's pl_poll, with the input
block as the boot leaves it, since wave 5's integration) on a2vm
under the test driver: each case staged in RamWorks (the wi state at
milestone 10's places through s2state's injection, PALST, WIW's own block,
the SCBs and palettes), the pixels poisoned with the run's fill, then
wi_frame in the cost phase 30. After each call a snapshot of the screen,
the wi state and the state blocks; the write log judges every writer (no
stray write) and the publish order (s2check.order).

Checks, for every case:
  - the whole screen ($2000-$9FFF: s2layout's regions 'wi' and 'colors';
    $9DC8-$9DFF kept) equal to the reference's after the frame;
  - WI_SNLPTR equal to the reference's at I_FinishUpdate (WI_Drawer sets
    it in NoState);
  - PALST's scb, palette and picturenum equal to the reference's at
    I_FinishUpdate;
  - no stray write, the publish order of SCREENS.md 1.3, the stack;
  - (chained) W_LUMPS, made by wi_init, equal to the reference's lumps as
    2D store handles.
Modes: 'injected' (each case from its own state; fill $A5 with the
screen's colours as captured, fill $5A with every byte the frame marked
poisoned) and 'chained' (each intermission's frames in order from the
first frame's state: PALST carried by the native code, W_LUMPS from
wi_init, the wi state injected each frame as milestone 10 makes it).

Usage:
  python3 tools/native/s2wi.py --inc OUT       the generated s2wi.inc
  python3 tools/native/s2wi.py --check [--profile f121] [--jobs 2]
  python3 tools/native/s2wi.py --planted [--jobs 2]
  python3 tools/native/s2wi.py --all [--jobs 2] (the checks, the timing on
                                    f121 and fastpath, the planted bugs,
                                    the sizes: build/native/m11/s2wi/
                                    report.json)
"""

