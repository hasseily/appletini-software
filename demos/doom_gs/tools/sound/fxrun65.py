#!/usr/bin/env python3
"""The effect player (src/sound/fx.s) on a2vm against its model
tools/sound/fxplay.py and S2's music player (milestone 11, part fxplay;
docs/m11-parts/fxplay.md).

Usage (from demos/doom_gs, after make -C src/native -f m11.mk part
P=fxplay):
  python3 tools/sound/fxrun65.py --cfg OUT      the test machine's ld65 map
  python3 tools/sound/fxrun65.py --checkpoint [--jobs N] [--quick]
  python3 tools/sound/fxrun65.py --cost [--jobs N]
  python3 tools/sound/fxrun65.py --timing [--jobs N]
  python3 tools/sound/fxrun65.py --planted [--jobs N]

The machine (build/native/m11/fxplay/fxt.*): src/sound/fxdrv.s and
fx_service in main memory at $0800; S2's player (build/sound65, read
only), pl_irq.s (pl_vbl the IRQ vector) and fx.s's card part at the
game's places (s2layout.py); the songs in RamWorks banks 1-13 at $1000;
SFX.1 in bank SFX (103) at $0200. a2vm runs it on the W65C02S with the
cost model on its clock (--cost-timed; the Doom profile f121+phasor+
window32 unless said), the AY log, --irq-bounds 00D8-01FF,C0A0-C0AF,
C400-C4FF,E000-FFFF (MEMORY_MAP.md rule 2), the lowest S in the handler,
and a write log of the effects' card state, the rings, S2's snd_playing
and the driver's drv_mark.

The oracle. The write log gives the time of each main-loop event (an
action, a frame's fx_service and snd_refill: drv_mark) and of fx_song's
steps (FX_HOLD, snd_playing); the AY log the time of each interrupt.
Taken in time order, the model runs each: an interrupt is S2's music
model (run65.RingPlayer, the song started by the latest snd_start) then
fxplay.FxPlayer.step(); an action is the driver's (fxdrv.s); a frame is
fx_service, then snd_refill. An interrupt may land inside a song's start
only (the hold test): there the model follows what the write log says
had happened (FX_HOLD set, the old song stopped, the new one playing).
Each interrupt's AY writes must equal the model's, write for write: the
music's (chips 0-2), then chip 3's. The main loop's writes (the chips'
resets, each song start's reset_chips) equal the model's between the
same interrupts (or, when an interrupt landed inside a song start, in
the same order over the run). At the end the four chips hold what the
model's writes leave; drv_qlog holds the model's fx_isplaying answers.

The write log also checks the publish order: every ring byte that a
store to V_WPOS publishes was written by the main loop after the voice's
previous publish (or its start), and the interrupt never writes a ring.

Every run is bounded (cycles, wall time, the logs' sizes) in a tempfile
directory under build/ that is deleted after it. Standard library only.
"""

