def make(m11: Path = M11, fxsrc: Path = SRC) -> None:
    """make -f m11.mk part P=fxplay into m11, fx.s and fxdrv.s from
    fxsrc; fails on a warning."""
    result = bounded.run(['make', '-s', '-C', str(NATIVE_SRC), '-f', 'm11.mk',
                          'part', 'P=fxplay', 'M11=%s' % m11,
                          'ROOT=%s' % ROOT, 'FXSRC=%s' % fxsrc],
                         timeout=300, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, universal_newlines=True)
    if result.returncode:
        raise RunError('the build failed:\n' + result.stdout)
    if 'arning' in result.stdout:
        raise RunError('the build warns:\n' + result.stdout)


def have_build(part: Path = PART) -> bool:
    return (part / 'fxt.map').exists() and SFX1.exists() and A2VM.exists()


class Linked(NamedTuple):
    dir: Path
    labels: Dict[str, int]
    segments: Dict[str, Tuple[int, int]]
    main: bytes
    lc: bytes


def load(part: Path = PART) -> Linked:
    return Linked(part, run65.read_labels(part / 'fxt.lbl'),
                  run65.segments(part / 'fxt.map'),
                  (part / 'fxt.main').read_bytes(),
                  (part / 'fxt.lc').read_bytes())


def sizes(part: Path = PART) -> Dict[str, int]:
    """The card part, fx_service and FXCODE in all (with pl_vbl)."""
    text = (part / 'fxt.map').read_text()
    mods = text.split('Modules list:', 1)[1].split('Segment list:', 1)[0]
    out, module = {}, None
    for line in mods.splitlines():
        if line and not line.startswith(' '):
            module = Path(line.strip().rstrip(':')).stem
            continue
        f = line.split()
        if module and f and f[0] in ('FXCODE', 'S2CODE'):
            size = int(next(x for x in f if x.startswith('Size='))[5:], 16)
            out['%s:%s' % (module, f[0])] = size
    seg = run65.segments(part / 'fxt.map')
    out['FXCODE'] = seg['FXCODE'][1]
    out['FXC_ROOM'] = S.FX_CODE[1] - S.FX_CODE[0]
    data = 4 * fxplay.NREGS + 1                 # want, shadow, the list
    out['card_data'] = data
    out['card_code'] = out['fx-card:FXCODE'] - data
    return out


