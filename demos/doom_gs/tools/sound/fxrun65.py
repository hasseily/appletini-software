def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--cfg')
    parser.add_argument('--checkpoint', action='store_true')
    parser.add_argument('--quick', action='store_true')
    parser.add_argument('--cost', action='store_true')
    parser.add_argument('--timing', action='store_true')
    parser.add_argument('--planted', action='store_true')
    parser.add_argument('--jobs', type=int, default=JOBS)
    args = parser.parse_args(argv)
    if args.cfg:
        S.write_if_changed(Path(args.cfg), cfg_text())
        return 0
    if not have_build():
        print('no build: make -C src/native -f m11.mk part P=fxplay, and '
              'SFX.1 (part fxconv)', file=sys.stderr)
        return 2
    bad = 0
    if args.checkpoint:
        bad += len(checkpoint(args.jobs, args.quick))
    if args.cost:
        bad += len(cost(args.jobs))
    if args.timing:
        bad += len(timing(args.jobs))
    if args.planted:
        bad += len(planted(args.jobs))
    return 1 if bad else 0


