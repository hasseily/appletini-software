def planted_variant(name: str, old: str, new: str, root: Path) -> Path:
    src = root / 'src'
    src.mkdir(parents=True)
    text = (SRC / 'fx.s').read_text()
    if text.count(old) != 1:
        raise RunError('planted %r: its text is not in fx.s once' % name)
    text = text.replace(old, new)
    if 'published before' in name:
        if text.count(PUBLISH_AFTER) != 1:
            raise RunError('planted %r: the later publish' % name)
        text = text.replace(PUBLISH_AFTER, ':\n')
    (src / 'fx.s').write_text(text)
    shutil.copy(str(SRC / 'fxdrv.s'), str(src / 'fxdrv.s'))
    return src


def scenario(kind: str, bank: bytes, songs: Sequence[bytes],
             part: Path) -> List[str]:
    """One scenario of the checkpoint on the build in `part`: its
    problems."""
    if kind == 'hold':
        return hold_check(songs[:3], part)
    if kind == 'songs':
        setup = over_song_setup(songs, 0, demo3_starts())
        k = None
    elif kind == 'stereo':
        setup, want = stereo_setup(bank)
        k = ('stereo', want)
    elif kind == 'underrun':
        setup, k = underrun_setup(bank), 'underrun'
    else:
        setup, k = alone_setup(bank, False, VOL_MID, 'A'), None
    p, res, ex = checked(setup, 'pl', part)
    return p + scenario_problems(k, res, ex, None)


def hold_check(songs, part, tries=40) -> List[str]:
    setup = hold_setup(songs, tries)
    work = tmpdir('cal')
    try:
        res = run(setup._replace(actions=(), seconds=0.3), work, part)
        cal = res.byte('drv_cal') | res.byte('drv_cal', 1) << 8
    finally:
        shutil.rmtree(str(work), ignore_errors=True)
    p, res, ex = checked(hold_delays(setup, cal, tries), 'hold', part)
    return p if ex.held else p + ['no VBL landed with FX_HOLD set']


def planted(jobs: int = JOBS, out=print) -> List[str]:
    """Each planted bug in a scratch copy, built apart, must fail its
    scenarios. Returns the bugs that were not caught."""
    bank = bank_bytes()
    songs = [p.read_bytes() for p in song_files()]

    def one(entry):
        name, old, new, kinds = entry
        root = tmpdir('planted')
        try:
            src = planted_variant(name, old, new, root)
            m11 = root / 'm11'
            make(m11, src)
            caught = []
            for kind in kinds:
                p = scenario(kind, bank, songs, m11 / 'fxplay')
                if p:
                    caught.append('%s: %s' % (kind, p[0]))
            return name, caught
        except RunError as e:
            return name, ['(the run) %s' % str(e).splitlines()[0]]
        finally:
            shutil.rmtree(str(root), ignore_errors=True)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        done = list(pool.map(one, PLANTED))
    missed = []
    for name, caught in done:
        out('%-58s %s' % (name, caught[0] if caught else 'NOT CAUGHT'))
        if not caught:
            missed.append(name)
    return missed


