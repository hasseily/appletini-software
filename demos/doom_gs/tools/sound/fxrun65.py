class Write(NamedTuple):
    clock: int
    pc: int
    addr: int
    old: int
    new: int


class Result(NamedTuple):
    state: Dict[str, Any]
    main: List[List[Any]]           # run65.group's
    bursts: List[List[Any]]
    times: List[Tuple[int, int]]    # (entry, RTI) clocks
    partial: Optional[List[Any]]
    writes: List[Write]
    ram: bytes                      # main 64 KB
    lc: bytes                       # $C000-$FFFF
    stack: Dict[str, Optional[int]]
    labels: Dict[str, int]
    fabric_mhz: float

    def byte(self, label: str, offset: int = 0) -> int:
        a = self.labels[label] + offset
        return self.lc[a - 0xC000] if a >= 0xC000 else self.ram[a]


def profile_name(setup: Setup) -> str:
    parts = setup.profile.split('+')
    if setup.ntsc and 'ntsc' not in parts:
        parts.append('ntsc')
    return '+'.join(parts)


def run(setup: Setup, work: Path, part: Path = PART) -> Result:
    d = load(part)
    lab = d.labels
    work.mkdir(parents=True, exist_ok=True)
    if len(setup.actions) > MAX_ACTIONS:
        raise RunError('%d actions, at most %d' % (len(setup.actions),
                                                   MAX_ACTIONS))
    main = bytearray(d.main)

    def poke(label, value):
        main[lab[label] - DRV_MAIN] = value
    poke('drv_mode', (1 if setup.count else 0) | (2 if setup.calibrate else 0))
    poke('drv_probe', 1 if setup.probe else 0)
    poke('drv_std', 0x80 if setup.ntsc else 0)
    poke('drv_gate', setup.gate)
    poke('drv_frame', setup.frame)
    table = b''.join(a.pack() for a in setup.actions) + b'\0'
    at = lab['drv_actions'] - DRV_MAIN
    main[at:at + len(table)] = table
    image = bytearray(b'A2VMIMG1')

    def record(kind, bank, address, data):
        image.extend(struct.pack('<BBHI', kind, bank, address, len(data)))
        image.extend(data)
    record(2, 0, LC_LO, d.lc)
    record(0, 0, DRV_MAIN, bytes(main))
    for k, data in enumerate(setup.songs):
        record(1, SONG_BANK0 + k, SONG_AT, data)
    record(1, SFX_BANK, SFX_AT, setup.bank or SFX1.read_bytes())
    (work / 'fx.img').write_bytes(bytes(image))
    (work / 'rom.bin').write_bytes(bytes(0x4000))
    name = profile_name(setup)
    (work / 'cost.txt').write_text(costs.text(name))
    fabric = costs.parameters(name)['fabric_mhz']
    fx_lo, fx_size = d.segments['FXCODE']
    snd_lo, snd_size = d.segments['SNDCODE']
    idle = lab['drv_idle']
    lowest = [(idle, idle + 5), (fx_lo, fx_lo + fx_size - 1),
              (snd_lo, snd_lo + snd_size - 1)]
    ranges = ','.join([
        'lc:%04X-%04X' % (S.FXV_BASE, S.FXV_END - 1),
        'lc:%04X-%04X' % (S.FX['FX_ON'], S.FX_RING - 1),
        'lc:%04X-%04X' % (S.FX_RING, S.FX_RING_END - 1),
        'lc:%04X' % lab['snd_playing'], 'main:%04X' % lab['drv_mark']])
    args = [str(A2VM), '--rom', str(work / 'rom.bin'),
            '--core', 'w65c02s', '--via-ora-nh',
            '--image', str(work / 'fx.img'),
            '--switch', 'lc_read=1', '--switch', 'lc_write=1',
            '--reg', 'pc=%X' % lab['drv_start'], '--reg', 's=FF',
            '--reg', 'p=34',
            '--cost', str(work / 'cost.txt'), '--cost-timed',
            '--cycles', str(int(round(setup.seconds * fabric * 1e6))),
            '--ay-log', str(work / 'ay.log'),
            '--state', str(work / 'state.json'),
            '--irq-bounds', IRQ_BOUNDS,
            '--lowest-s-in', ','.join('%X-%X' % r for r in lowest),
            '--write-log', ranges,
            '--write-log-file', str(work / 'writes.log'),
            '--write-log-limit', str(WRITE_LOG_LIMIT),
            '--snapshot-dir', str(work), '--final-snapshot',
            '--stop-pc', '%X' % lab['drv_halt'],
            '--stop-pc', '%X' % lab['pl_crash']]
    if setup.mb_only:
        args.append('--phasor-mb-only')
    if not setup.count:
        args += ['--idle', '%X:vbl:eq=%X,%X' % (idle, lab['vbl_count'],
                                                lab['drv_seen'])]
    try:
        result = bounded.run(args, timeout=RUN_TIMEOUT, max_bytes=MAX_FILE,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             universal_newlines=True)
    except subprocess.TimeoutExpired:
        raise RunError('a2vm did not finish in %d s' % RUN_TIMEOUT)
    state_path = work / 'state.json'
    if result.returncode or not state_path.exists():
        halt = ''
        if state_path.exists():
            halt = json.loads(state_path.read_text()).get('halt', '')
        raise RunError('a2vm failed: %s\n%s' % (halt, result.stdout[-2000:]))
    state = json.loads(state_path.read_text())
    if state['end'] != 'cycles':
        raise RunError('the run ended early (%s at $%04X%s)' % (
            state['end'], state['pc'],
            ': ' + state['halt'] if state.get('halt') else ''))
    events = run65.read_log(work / 'ay.log')
    mains, bursts, times, partial = run65.group(events)
    writes = read_writes(work / 'writes.log')
    snap = (work / 'final.ram').read_bytes()
    low = state.get('lowest_s', {}).get('ranges', [])
    stack = {'idle': low[0].get('s') if low else None,
             'handler': min((x['s'] for x in low[1:]
                             if x.get('s') is not None), default=None)}
    return Result(state, mains, bursts, times, partial, writes,
                  snap[:0x10000], snap[0x10000:0x14000], stack, lab, fabric)


def read_writes(path: Path) -> List[Write]:
    out = []
    with open(path) as log:
        for line in log:
            if not line.startswith('w '):
                continue
            f = line.split()
            out.append(Write(int(f[1]), int(f[3], 16), int(f[4], 16),
                             int(f[8], 16), int(f[9], 16)))
    return out


def depth(stack: Dict[str, Optional[int]]) -> Optional[int]:
    """The interrupt's stack depth: S where it came (an entry in the idle
    loop, 3 bytes below its S) less the lowest S in the handler's code (as
    tools/native/plclock.py)."""
    top, low = stack.get('idle'), stack.get('handler')
    if top is None or low is None:
        return None
    return top + 3 - low


