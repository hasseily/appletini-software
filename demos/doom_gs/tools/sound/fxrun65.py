class Event(NamedTuple):
    value: int          # an action's kind, or MARK_FRAME
    start: int
    end: int


def main_events(res: Result) -> List[Event]:
    mark = res.labels['drv_mark']
    out, cur = [], None
    for w in res.writes:
        if w.addr != mark:
            continue
        if w.new == 0:
            if cur is not None:
                out.append(Event(cur[0], cur[1], w.clock))
                cur = None
        elif cur is None:
            cur = (w.new, w.clock)
        elif not (cur[0] == MARK_FRAME and w.new == MARK_REFILL):
            raise RunError('drv_mark $%02X inside $%02X' % (w.new, cur[0]))
    if cur is not None:
        out.append(Event(cur[0], cur[1], 1 << 62))
    return out


class Expect(NamedTuple):
    gaps: List[List[Any]]           # the main loop's writes after irq k
    bursts: List[List[Any]]
    queries: List[int]
    fx: fxplay.FxPlayer
    held: List[int]                 # interrupts with FX_HOLD at entry
    starved: List[int]              # interrupts where a voice starved
    choices: List[Tuple[int, int, int]]     # (voice, channel, sound)
    inside: bool                    # an interrupt landed in a song start
    problems: List[str]


class ChoiceLog(fxplay.FxPlayer):
    """fxplay.FxPlayer that records each start's voice."""

    def __init__(self, *a, **k):
        self.choices = []
        super().__init__(*a, **k)

    def start(self, v, c, m):
        self.choices.append((self.voices.index(v), c, m.sound))
        super().start(v, c, m)


def expect(setup: Setup, res: Result) -> Expect:
    bank = setup.bank or SFX1.read_bytes()
    fx = ChoiceLog(bank, ntsc=setup.ntsc)
    answer = fxplay.SND_NO_MUSIC if (setup.probe and setup.mb_only) \
        else fxplay.SND_MUSIC
    fx.init(answer)
    music = answer == fxplay.SND_MUSIC
    problems: List[str] = []
    gaps: List[List[Any]] = [list(run65.init_events(setup.probe,
                                                   setup.mb_only))]
    bursts: List[List[Any]] = []
    queries: List[int] = []
    held: List[int] = []
    starved: List[int] = []
    events = main_events(res)
    nact = sum(1 for e in events if e.value != MARK_FRAME)
    if nact != len(setup.actions):
        problems.append('%d actions ran, %d given' % (nact, len(setup.actions)))
    hold_at = S.FX['FX_HOLD']
    play_at = res.labels['snd_playing']
    points: List[Tuple[int, int, str, Any]] = []
    for k, (entry, _) in enumerate(res.times, 1):
        points.append((entry, 1, 'irq', k))
    inside = False
    acts = iter(setup.actions)
    for e in events:
        if e.value == MARK_FRAME:
            points.append((e.start, 0, 'frame', None))
            continue
        act = next(acts, None)
        if act is None:
            break
        if act.kind != e.value:
            problems.append('action %s ran as kind %d' % (act, e.value))
            break
        within = [w for w in res.writes if e.start <= w.clock <= e.end]
        if act.kind == SONG and music:
            seq = [(w.clock, 'hold' if w.new else 'release')
                   for w in within if w.addr == hold_at] + \
                  [(w.clock, 'on' if w.new else 'off')
                   for w in within if w.addr == play_at]
            if sorted(x[1] for x in seq) != ['hold', 'off', 'on', 'release']:
                problems.append('a song start without its four steps: %s'
                                % seq)
            for clock, step in seq:
                points.append((clock, 0, 'song-' + step, act))
        else:
            points.append((e.start, 0, 'act', act))
        n_in = [k for k, (entry, _) in enumerate(res.times, 1)
                if e.start < entry < e.end]
        if n_in:
            if act.kind == SONG:
                inside = True
            else:
                problems.append('interrupt %d inside %s: the model cannot '
                                'place it' % (n_in[0], KINDS[act.kind]))
    for e in events:
        if e.value == MARK_FRAME:
            n_in = [k for k, (entry, _) in enumerate(res.times, 1)
                    if e.start < entry < e.end]
            if n_in:
                problems.append('interrupt %d inside a frame\'s service: the '
                                'model cannot place it' % n_in[0])
    points.sort(key=lambda p: (p[0], p[1]))
    state = {'cur': None, 'new': None, 'gate': setup.gate}

    def do_act(act):
        a = act.args
        if act.kind == START:
            fx.mail_start(a[0], a[1], a[2], a[3])
        elif act.kind == STOP:
            fx.mail_stop(a[0])
        elif act.kind == VOLUME:
            fx.mail_volume(a[0], a[1])
        elif act.kind == GATE:
            state['gate'] = a[0]
        elif act.kind == STOPALL:
            fx.stopall()
        elif act.kind == QUERY:
            queries.append(sum(1 << c for c in range(fxplay.NUM_CHANNELS)
                               if fx.isplaying(c)))
        elif act.kind == SERVICE:
            fx.service()
        elif act.kind == SONGSTOP:
            if music and state['cur'] is not None:
                state['cur'].stop()

    for clock, _, what, arg in points:
        if what == 'irq':
            cur = state['cur']
            mus = cur.interrupt() if cur is not None else []
            if fx.hold:
                held.append(arg)
            w = fx.step()
            if any(v.flags & fxplay.STARVED for v in fx.voices):
                starved.append(arg)
            bursts.append(list(mus) + list(w))
            gaps.append([])
        elif what == 'frame':
            if state['gate'] & 1:
                fx.service()
            cur = state['cur']
            if state['gate'] & 2 and music and cur is not None and \
                    cur.playing:
                cur.refill()
        elif what == 'act':
            do_act(arg)
        elif what == 'song-hold':
            fx.song_begin()
        elif what == 'song-off':
            state['cur'] = None
            index = arg.args[0] - SONG_BANK0
            p = run65.RingPlayer(
                player.SongFile.from_bytes(setup.songs[index]),
                run65.machine_of(bool(arg.args[3] & SONG_NTSC)),
                loop=bool(arg.args[3] & SONG_LOOP),
                music_attenuation=arg.args[4])
            gaps[-1].extend(p.start())
            state['new'] = p
        elif what == 'song-on':
            state['cur'] = state['new']
        elif what == 'song-release':
            fx.song_end()
    return Expect(gaps, bursts, queries, fx, held, starved, fx.choices,
                  inside, problems)


def publish_problems(res: Result) -> List[str]:
    """Every ring byte a V_WPOS store publishes was written by the main
    loop since the voice's previous publish or start; no interrupt writes
    a ring."""
    out = []
    entries = [a for a, _ in res.times]

    def in_irq(clock):
        k = bisect.bisect_right(entries, clock) - 1
        return k >= 0 and clock <= res.times[k][1]
    for v in range(fxplay.VOICES):
        base = S.FX_RING + v * fxplay.RING
        wpos = S.FXV_BASE + v * S.VOICE_SIZE + S.VOICE['V_WPOS']
        fresh = set()
        for w in res.writes:
            if base <= w.addr < base + fxplay.RING:
                if in_irq(w.clock):
                    out.append('the interrupt wrote ring %d at $%04X (pc $%04X)'
                               % (v, w.addr, w.pc))
                fresh.add(w.addr - base)
            elif w.addr == wpos:
                if res.ram[w.pc] == 0x9E:           # stz abs,x: a start
                    fresh = set()
                    continue
                n = (w.new - w.old) & 0xFF
                if not 1 <= n <= fxplay.RING:
                    out.append('voice %d: V_WPOS $%02X to $%02X' % (
                        v, w.old, w.new))
                    continue
                for k in range(n):
                    off = (w.old + k) & (fxplay.RING - 1)
                    if off not in fresh:
                        out.append('voice %d: byte %d of the ring published '
                                   'at clock %d before it was written (pc '
                                   '$%04X)' % (v, off, w.clock, w.pc))
                        break
                    fresh.discard(off)
            if len(out) > 5:
                return out
    return out


def compare(setup: Setup, res: Result, ex: Expect) -> List[str]:
    """The run against the model: every interrupt's writes, the main
    loop's, the chips at the end, the answers of fx_isplaying, the burst
    order (chip 3 after the music's), the publish order."""
    out = list(ex.problems)
    if len(res.bursts) != len(ex.bursts):
        out.append('%d interrupts, the model %d' % (len(res.bursts),
                                                    len(ex.bursts)))
    for k, (got, want) in enumerate(zip(res.bursts, ex.bursts), 1):
        chips = [w[0] for w in got if w[0] != 'reset']
        if 3 in chips and any(c != 3 for c in chips[chips.index(3):]):
            out.append('interrupt %d: a write of chip 0-2 after chip 3\'s: %s'
                       % (k, got[:8]))
            break
        if got != want:
            music_got = [w for w in got if w[0] != 3]
            music_want = [w for w in want if w[0] != 3]
            which = 'chips 0-2' if music_got != music_want else 'chip 3'
            out.append('interrupt %d (%s): %s' % (
                k, which, run65.first_difference(got, want)))
            break
    if ex.inside:
        flat = [w for g in res.main for w in g]
        want = [w for g in ex.gaps for w in g]
        if flat != want:
            out.append('the main loop\'s writes: %s' % run65.first_difference(
                flat, want))
    else:
        for k, (got, want) in enumerate(zip(res.main, ex.gaps)):
            if got != want:
                out.append('main loop after interrupt %d: %s' % (
                    k, run65.first_difference(got, want)))
                break
    regs = [[0] * 16 for _ in range(4)]

    def apply(ws):
        for w in ws:
            if w[0] == 'reset':
                regs[w[1]] = [0] * 16
            else:
                regs[w[0]][w[1]] = w[2]
    apply(ex.gaps[0])
    for k, b in enumerate(ex.bursts):
        apply(b)
        if k + 1 < len(ex.gaps):
            apply(ex.gaps[k + 1])
    if res.partial:
        apply(res.partial)
    if not setup.mb_only:
        for chip in range(4):
            if res.state['phasor']['ay'][chip] != regs[chip]:
                out.append('at the end chip %d holds %s, the model %s' % (
                    chip, res.state['phasor']['ay'][chip], regs[chip]))
    nq = res.byte('drv_nq')
    got_q = [res.byte('drv_qlog', k) for k in range(nq)]
    if got_q != ex.queries[:QLOG]:
        out.append('fx_isplaying: %s, the model %s' % (got_q, ex.queries))
    out += publish_problems(res)
    return out


