COST_VARIANTS = (('window 512', 'f121+phasor'),
                 ('window 32', 'f121+phasor+window32'),
                 ('FW-S1', 'f121+phasor+fws1'))


def cycling_actions(bank: bytes, voices: int, seconds: float,
                    with_song: bool) -> Tuple[Act, ...]:
    """`voices` channels each playing the 52 effects in turn, back to
    back (a start every effect's length)."""
    acts = [song(0, 0)] if with_song else []
    end = int(seconds * 50) - 5
    lengths = {s: effect_length(bank, s) for s in range(1, 53)}
    plans = []
    for c in range(voices):
        t, s = 3 + 7 * c, 1 + 17 * c
        while t < end:
            plans.append(start(t, c, (s - 1) % 52 + 1, VOL_NEAR,
                               (SEP_LEFT, SEP_RIGHT, SEP_CENTRE)[c]))
            t += lengths[(s - 1) % 52 + 1] + 1
            s += 1
    plans.sort(key=lambda a: a.vbl)
    acts += plans[:MAX_ACTIONS - len(acts)]
    return tuple(acts)


def cost(jobs: int = JOBS, seconds: float = 20.0, out=print) -> List[str]:
    """The effects' cost a second (1 and 3 voices; window 512, 32, FW-S1)
    as the time they take from the main loop (drv_count against a run
    without them), the part spent in the interrupt, and the slowdown
    tail: the main loop's time lost beyond the interrupts, a burst of
    chip 3 (with no music every burst of chip 3 is an interrupt where
    only the effects write); over D_E1M1, the extra tail the effects add
    to the song's, a burst where only the effects write."""
    bank = bank_bytes()
    songs = (song_files()[0].read_bytes(),)
    tasks = []
    for label, prof in COST_VARIANTS:
        for n in (0, 1, 3):
            acts = cycling_actions(bank, n, seconds, False) if n else ()
            tasks.append((label, n, False, Setup(acts, seconds, count=True,
                                                 profile=prof)))
        for n in (0, 3):
            acts = cycling_actions(bank, n, seconds, True) if n else \
                (song(0, 0),)
            tasks.append((label, n, True, Setup(acts, seconds, songs=songs,
                                                count=True, profile=prof)))
        # the integration's report (docs/SCREENS.md 8.3 item 2): D_E1M1
        # with the effects at demo3's measured start times, and with three
        # effects started in one VBL again and again (the worst case)
        tasks.append((label, 'demo3', True, over_song_setup(
            songs, 0, demo3_starts(), seconds)._replace(
                count=True, profile=prof)))
        tasks.append((label, 'three', True, three_setup(
            songs, prof, seconds)._replace(count=True)))

    def one(task):
        work = tmpdir('cost')
        try:
            return task, run(task[3], work)._replace(writes=[])
        finally:
            shutil.rmtree(str(work), ignore_errors=True)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        done = list(pool.map(one, tasks))
    rows = {(label, n, m): res for (label, n, m, _), res in done}

    def figures(r, base):
        ms = 1000.0 * (1 - counter(r) / counter(base))
        irq = (sum(b - a for a, b in r.times) -
               sum(b - a for a, b in base.times)) / r.fabric_mhz / 1000.0 \
            / seconds
        return ms, irq
    out('Without music (the cost a second, ms of 1,000):')
    out('')
    out('| Setting | effects | from the main loop | in the interrupt | '
        'tail | chip-3 writes/s | bursts/s | tail a burst |')
    out('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
    for label, _ in COST_VARIANTS:
        base = rows[(label, 0, False)]
        for n in (1, 3):
            r = rows[(label, n, False)]
            ms, irq = figures(r, base)
            bursts = sum(1 for b in r.bursts if any(w[0] == 3 for w in b))
            w3 = sum(1 for b in r.bursts for w in b if w[0] == 3)
            out('| %s | %d | %.2f | %.2f | %.2f | %.0f | %.1f | %.0f µs |' % (
                label, n, ms, irq, ms - irq, w3 / seconds, bursts / seconds,
                1000.0 * (ms - irq) / (bursts / seconds)))
    out('')
    out('Over D_E1M1 (three effects; the song alone as the base):')
    out('')
    out('| Setting | the song alone | with the effects | the effects: in '
        'the interrupt, tail | bursts with the music\'s, alone, a second | '
        'extra tail a burst of their own |')
    out('| --- | ---: | ---: | --- | --- | ---: |')
    nothing = {label: rows[(label, 0, False)] for label, _ in COST_VARIANTS}
    for label, _ in COST_VARIANTS:
        alone, both = rows[(label, 0, True)], rows[(label, 3, True)]
        ms0, irq0 = figures(alone, nothing[label])
        ms3, irq3 = figures(both, nothing[label])
        shared = own = 0
        for b in both.bursts:
            if any(w[0] == 3 for w in b):
                if any(w[0] != 3 for w in b):
                    shared += 1
                else:
                    own += 1
        tail = (ms3 - irq3) - (ms0 - irq0)
        out('| %s | %.2f ms/s | %.2f ms/s | %.2f, %.2f ms/s | %.1f, %.1f | '
            '%.0f µs |' % (label, ms0, ms3, irq3 - irq0, tail,
                           shared / seconds, own / seconds,
                           1000.0 * tail / (own / seconds) if own else 0))
    out('')
    out('Over D_E1M1: the song alone, the effects at demo3\'s measured start '
        'times, three effects started in one VBL every 45 (ms of 1,000 a '
        'second from the main loop: in the interrupt, tail; the worst '
        'interrupt):')
    out('')
    out('| Setting | the song alone | demo3\'s start rate (starts) | three '
        'at once | worst interrupt: alone, demo3, three |')
    out('| --- | --- | --- | --- | --- |')

    def worst(r):
        return max((b - a for a, b in r.times), default=0) / r.fabric_mhz
    for label, _ in COST_VARIANTS:
        base = nothing[label]
        cells = []
        for key in (0, 'demo3', 'three'):
            r = rows[(label, key, True)]
            ms, irq = figures(r, base)
            cells.append('%.2f ms/s (%.2f, %.2f)' % (ms, irq, ms - irq))
        setup = next(task[3] for task, _ in done
                     if task[0] == label and task[1] == 'demo3')
        cells[1] += ' (%d)' % sum(1 for a in setup.actions
                                  if a.kind == START)
        out('| %s | %s | %.1f, %.1f, %.1f µs |' % (
            label, ' | '.join(cells), worst(rows[(label, 0, True)]),
            worst(rows[(label, 'demo3', True)]),
            worst(rows[(label, 'three', True)])))
    return []


def counter(res: Result) -> int:
    a = res.labels['drv_counter']
    return int.from_bytes(res.ram[a:a + 4], 'little')


def summary(pairs) -> str:
    if not pairs:
        return '-'
    extra = statistics.median(p[0] for p in pairs)
    writes = statistics.median(p[1] for p in pairs)
    one = [p[0] for p in pairs if p[1] == 1]
    return '%.1f µs, %g writes (%d interrupts; 1 write: %s)' % (
        extra, writes, len(pairs),
        '%.1f µs' % statistics.median(one) if one else '-')


def timing(jobs: int = JOBS, out=print) -> List[str]:
    """fx_service a frame (docs/SCREENS.md 6.4): three effects, music on,
    a frame every VBL (50 a second) and every 8 (6 a second), f121 and
    fastpath (the Doom profile's window 32)."""
    bank = bank_bytes()
    songs = [song_files()[0].read_bytes()]
    tasks = []
    for prof in ('f121+phasor+window32', 'fastpath+phasor+window32'):
        for frame in (1, 8):
            acts = cycling_actions(bank, 3, 20.0, True)
            tasks.append((prof, frame, Setup(acts, 20.0, songs=tuple(songs),
                                             profile=prof, frame=frame)))

    def one(task):
        prof, frame, setup = task
        work = tmpdir('time')
        try:
            res = run(setup, work)
            return task, frame_times(res), res
        finally:
            shutil.rmtree(str(work), ignore_errors=True)
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        done = list(pool.map(one, tasks))
    out('| Profile | frames a second | fx_service median / p99 / worst µs '
        '| frames |')
    out('| --- | ---: | --- | ---: |')
    for (prof, frame, _), t, res in done:
        hz = 50.08 / frame
        if not t:
            out('| %s | %.1f | - | 0 |' % (prof, hz))
            continue
        t.sort()
        out('| %s | %.1f | %.1f / %.1f / %.1f | %d |' % (
            prof, hz, statistics.median(t), t[min(len(t) - 1,
                                                  int(len(t) * 0.99))],
            t[-1], len(t)))
    return []


def frame_times(res: Result) -> List[float]:
    """Each frame's fx_service in µs (drv_mark $80 to $81), an
    interrupt inside it left out."""
    mark = res.labels['drv_mark']
    out, begin = [], None
    for w in res.writes:
        if w.addr != mark:
            continue
        if w.new == MARK_FRAME:
            begin = w.clock
        elif w.new == MARK_REFILL and begin is not None:
            if not any(begin < a < w.clock for a, _ in res.times):
                out.append((w.clock - begin) / res.fabric_mhz)
            begin = None
    return out


