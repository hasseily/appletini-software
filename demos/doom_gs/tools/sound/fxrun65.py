def bank_bytes() -> bytes:
    return SFX1.read_bytes()


def effect_length(bank: bytes, sound: int, ntsc: bool = False) -> int:
    """Interrupts from an effect's first one to its voice's last write
    (alone, full volume), by the model."""
    fx = fxplay.FxPlayer(bank, ntsc=ntsc)
    fx.mail_start(0, sound, VOL_NEAR, SEP_CENTRE)
    fx.service()
    for k in range(1, 2000):
        fx.interrupt()
        fx.service()
        if not any(v.flags for v in fx.voices):
            return k
    raise RunError('effect %d never ends' % sound)


def song_files() -> List[Path]:
    return sorted(SONGS.glob('D_*.native12.ay'))


def alone_setup(bank: bytes, ntsc: bool, vol: int, voice: str,
                sounds: Sequence[int] = range(1, 53)) -> Setup:
    """Every effect alone, one after the other, on voice A, B or C."""
    acts, t = [], 2
    for s in sounds:
        if voice == 'A':
            acts.append(start(t, 0, s, vol, SEP_LEFT))
        elif voice == 'B':
            acts.append(start(t, 0, s, vol, SEP_RIGHT))
        else:           # C: A taken in the same gap, then freed before
            acts += [start(t, 0, s, vol, SEP_LEFT),      # any interrupt
                     start(t, 1, s, vol, SEP_LEFT),
                     other(SERVICE, t), stop(t, 0)]
        t += effect_length(bank, s, ntsc) + 2
    hz = tables.vbl_hz(run65.machine_of(ntsc))
    return Setup(tuple(acts), t / hz + 0.3, ntsc=ntsc, bank=bank)


def demo3_starts() -> List[int]:
    """demo3's S_StartSound and S_StartSound2 calls: their gametics."""
    import s2cap
    calls = s2cap.load_calls(CASES / 'demo3' / 'calls.z')
    starts = calls.of('S_StartSound') + calls.of('S_StartSound2')
    starts.sort(key=lambda c: c['call'])
    return [int.from_bytes(bytes.fromhex(c['in']['mem'][1]), 'little')
            for c in starts]


VOLS = (VOL_NEAR, 90, VOL_MID, 30, VOL_FAR)
SEPS = (SEP_CENTRE, 127, 129, SEP_LEFT, SEP_RIGHT, 1, 255)


def over_song_setup(songs: Sequence[bytes], index: int, gametics: List[int],
                    seconds: float = 20.0, ntsc: bool = False) -> Setup:
    """Song `index` from VBL 0, the effects at demo3's measured times
    (gametics at 34.955 a second, from VBL 10), each of the 52 in turn."""
    hz = tables.vbl_hz(run65.machine_of(ntsc))
    first = gametics[0]
    acts = [song(0, 0, ntsc)]
    k = 0
    for g in gametics:
        vbl = 10 + int(round((g - first) * hz / 34.955))
        if vbl > seconds * hz - 10 or len(acts) >= MAX_ACTIONS:
            break
        acts.append(start(vbl, k % 3, (k + 7 * index) % 52 + 1,
                          VOLS[k % len(VOLS)], SEPS[k % len(SEPS)]))
        k += 1
    return Setup(tuple(acts), seconds, ntsc=ntsc, songs=(songs[index],))


def three_setup(songs: Sequence[bytes], profile: str = PROFILE,
                seconds: float = 20.0, index: int = 0) -> Setup:
    """Song `index` with three effects started in one VBL, again and again
    (the worst interrupt, the stack). The first three start with the
    song's first burst: their mailboxes at VBL 0, the song at VBL 1, so
    the song's first interrupt (its first chord, the music's largest
    burst in D_INTRO) is the effects' first, a whole chip 3."""
    acts = [start(0, c, (2, 9, 15)[c], VOL_NEAR,
                  (SEP_LEFT, SEP_RIGHT, SEP_CENTRE)[c]) for c in range(3)]
    acts.append(song(1, 0))
    t, k = 25, 0
    while t < seconds * 50 - 60 and len(acts) + 3 <= MAX_ACTIONS:
        for c in range(3):
            acts.append(start(t, c, (3 * k + c) % 52 + 1, VOL_NEAR,
                              (SEP_LEFT, SEP_RIGHT, SEP_CENTRE)[c]))
        t += 45
        k += 1
    return Setup(tuple(acts), seconds, songs=(songs[index],),
                 profile=profile)


def underrun_setup(bank: bytes) -> Setup:
    """DORCLS (460 B) with fx_service gated off for 40 VBLs: its ring runs
    dry, the voice is silent and holds, then goes on."""
    s = 15
    acts = (start(2, 0, s), other(GATE, 3, 2), other(GATE, 43, 3),
            start(160, 1, 6, VOL_MID, SEP_RIGHT), other(GATE, 165, 2),
            other(GATE, 190, 3))
    return Setup(acts, 6.0, bank=bank)


def hold_setup(songs: Sequence[bytes], tries: int = 40) -> Setup:
    """Song starts while an effect plays, each after a delay a step
    longer, so that some VBLs land inside fx_song (calibrated delays)."""
    acts = []
    t = 4
    for i in range(tries):
        acts.append(start(t, i % 3, (5, 6, 15)[i % 3], VOL_NEAR,
                          (SEP_LEFT, SEP_RIGHT, SEP_CENTRE)[i % 3]))
        acts.append(song(t + 3, i % len(songs), delay=0))
        acts[-1] = acts[-1]._replace(delay=-(i + 1))    # placeholder
        t += 12
    return Setup(tuple(acts), (t + 20) / 50.0, songs=tuple(songs),
                 calibrate=True)


HOLD_SWEEP = 2.5       # the delay loop's turn is about half the
                       # calibration loop's [M: 45 and 90 fabric clocks]


def hold_delays(setup: Setup, cal: int, tries: int) -> Setup:
    """The song starts' delays: a step of HOLD_SWEEP x cal / tries, so the
    starts sweep a frame and more."""
    acts = []
    for a in setup.actions:
        if a.kind == SONG and a.delay < 0:
            i = -a.delay - 1
            a = a._replace(delay=min(0xFFFF, int(cal * HOLD_SWEEP *
                                                 (i + 0.5) / tries)))
        acts.append(a)
    return setup._replace(actions=tuple(acts))


def stereo_setup(bank: bytes) -> Tuple[Setup, List[str]]:
    """The stereo rule (each band and its bounds, the fallbacks with each
    voice busy, the channel's own voice freed first), the
    mailboxes' rules, fx_isplaying, the noise of the loudest. Returns the
    setup and the voices the starts must take, in order."""
    long_ = 15                          # DORCLS: 176 ticks
    acts, want = [], []
    t = 2

    def gap(n=1):
        nonlocal t
        t += n

    def stopall():
        acts.append(other(STOPALL, t))
    # alone, each band and its bounds (tools/sound/README.md "Stereo by
    # voice": A left, B right, C centre): below 96 A, 96 to 160 C, above
    # 160 B. The voices are written here, not taken from tables.py
    for sep, v in ((1, 'A'), (95, 'A'), (96, 'C'), (128, 'C'), (129, 'C'),
                   (160, 'C'), (161, 'B'), (255, 'B')):
        acts.append(start(t, 0, 1, VOL_NEAR, sep))
        want.append(v)
        gap(8)
        stopall()
        gap(3)
    # the fallbacks, to the nearest free voice in pan: three starts on
    # channels 0, 1, 2, each while the earlier ones play
    for case in (((128, 'C'), (128, 'A'), (100, 'B')),   # C busy: 128 left
                 ((129, 'C'), (160, 'B'), (140, 'A')),   # right of centre
                 ((50, 'A'), (95, 'C'), (1, 'B')),       # A busy: C, then B
                 ((200, 'B'), (161, 'C'), (255, 'A'))):  # B busy: C, then A
        for c, ((sep, v), sound) in enumerate(zip(case, (long_, 6, 1))):
            acts.append(start(t, c, sound, VOL_MID if c else VOL_NEAR, sep))
            want.append(v)
            gap(2)
        gap(18)
        stopall()
        gap(3)
    # a channel's own voice is freed first: A and B busy, channel 0 on C
    # at 128, then again at 1 (A first: busy; its own C freed)
    acts += [start(t, 1, long_, VOL_MID, 64), start(t, 2, long_, VOL_MID,
                                                    200)]
    want += ['A', 'B']
    gap(2)
    acts.append(start(t, 0, long_, VOL_NEAR, 128))
    want.append('C')
    gap(3)
    acts.append(start(t, 0, 6, VOL_NEAR, 1))
    want.append('C')
    gap(20)
    stopall()
    gap(3)
    # the mailboxes: a start then a stop in one frame: no voice
    acts += [start(t, 0, long_), other(QUERY, t), stop(t, 0),
             other(QUERY, t)]
    gap(5)
    acts.append(other(QUERY, t))
    gap(2)
    # a stop then a start: the new sound
    acts.append(start(t, 0, long_, VOL_NEAR, 64))
    want.append('A')
    gap(10)
    acts += [stop(t, 0), start(t, 0, 6, VOL_MID, 200), other(QUERY, t)]
    want.append('B')
    gap(10)
    acts.append(other(QUERY, t))
    # a start then a volume: the new volume
    acts += [start(t, 1, long_, VOL_NEAR, 64), volume(t, 1, 20)]
    want.append('A')
    gap(30)
    acts += [volume(t, 1, VOL_MID)]
    gap(20)
    stopall()
    gap(3)
    # the noise of the loudest: two noisy effects, the louder first (A)
    # and the quieter last (B), then the louder last
    acts += [start(t, 0, 9, VOL_NEAR, 64), start(t, 1, 49, 20, 200)]
    want += ['A', 'B']
    gap(60)
    stopall()
    gap(3)
    acts += [start(t, 0, 9, 20, 64), start(t, 1, 49, VOL_NEAR, 200)]
    want += ['A', 'B']
    gap(60)
    # fx_isplaying after the natural end of a sound
    acts.append(other(QUERY, t))
    gap(150)
    acts.append(other(QUERY, t))
    gap(5)
    return Setup(tuple(acts), t / 50.0 + 0.2, bank=bank), want


class NoiseWatch(fxplay.FxPlayer):
    """fxplay.FxPlayer that counts the composes where the loudest voice
    with noise and the last voice with noise have different periods (where
    the rule can be told from "the last voice's")."""

    telling = 0

    def compose(self):
        noisy = [(min(fxplay.ATT_SILENT, v.att + v.vatt), k, v.noise)
                 for k, v in enumerate(self.voices)
                 if v.flags & (fxplay.ACTIVE | fxplay.STARVED) ==
                 fxplay.ACTIVE and v.noise]
        if len(noisy) > 1 and min(noisy)[2] != noisy[-1][2]:
            self.telling += 1
        super().compose()


def noise_telling(bank: bytes, setup: Setup) -> int:
    """How many interrupts of `setup` (its effects, no music, one frame a
    VBL) tell the loudest voice's noise from the last one's, by the
    model."""
    fx = NoiseWatch(bank)
    acts = sorted(setup.actions, key=lambda a: a.vbl)
    i = 0
    for k in range(max(a.vbl for a in acts) + 10):
        while i < len(acts) and acts[i].vbl <= k:
            a = acts[i]
            if a.kind == START:
                fx.mail_start(*a.args[:4])
            elif a.kind == STOP:
                fx.mail_stop(a.args[0])
            elif a.kind == VOLUME:
                fx.mail_volume(a.args[0], a.args[1])
            elif a.kind == STOPALL:
                fx.stopall()
            elif a.kind == SERVICE:
                fx.service()
            i += 1
        fx.service()
        fx.interrupt()
    return fx.telling


def tone_first(bank: bytes) -> int:
    """The first effect whose first state has a tone."""
    for s in range(1, 53):
        fx = fxplay.FxPlayer(bank)
        fx.mail_start(0, s, VOL_NEAR, SEP_CENTRE)
        fx.service()
        fx.interrupt()
        if fx.chan_voice(0).per:
            return s
    raise RunError('no effect starts with a tone')


