def cfg_text() -> str:
    card = {name: (lo, hi) for name, lo, hi in S.S2_CARD}

    def area(name, lo, hi, file, extra=''):
        return '    %-7s start = $%04X, size = $%04X, %sfile = %s;\n' % (
            name + ':', lo, hi - lo, extra, file)
    out = ('# Generated by tools/sound/fxrun65.py --cfg (part fxplay;\n'
           '# s2layout.py\'s places). Do not edit.\nMEMORY {\n')
    out += area('DRVZP', DRVZP, DRVZP + 0x40, '""', 'type = rw, ')
    out += area('SNDZP', S.ZP_MUSIC[0], S.ZP_FXRING[0], '""', 'type = rw, ')
    out += area('MAIN', DRV_MAIN, 0x2000, '"%O.main"', 'type = rw, ')
    for key, name in (('RING', 'the song ring and its mirror'),
                      ('LIST', 'the player\'s write lists'),
                      ('STATE', 'the player\'s state')):
        out += area(key, card[name][0], card[name][1], '""', 'type = rw, ')
    r = card['S2\'s code and tables']
    out += area('SND', r[0], r[1], '"%O.lc"', 'fill = yes, ')
    out += area('FXC', S.FX_CODE[0], S.FX_CODE[1], '"%O.lc"', 'fill = yes, ')
    out += area('REST', S.FX_CODE[1], 0xFFFA, '"%O.lc"', 'fill = yes, ')
    out += area('VEC', 0xFFFA, 0x10000, '"%O.lc"')
    out += '}\nSEGMENTS {\n'
    rows = [('SNDZP', 'SNDZP', 'type = zp'), ('DRVZP', 'DRVZP', 'type = zp'),
            ('DRVCODE', 'MAIN', 'type = rw'),
            ('S2CODE', 'MAIN', 'type = rw, define = yes'),
            ('DRVDATA', 'MAIN', 'type = rw'),
            ('SNDBOOT', 'MAIN', 'type = rw'),
            ('SNDRING', 'RING', 'type = bss, align = $100'),
            ('SNDLIST', 'LIST', 'type = bss'),
            ('SNDBSS', 'STATE', 'type = bss'),
            ('SNDCODE', 'SND', 'type = ro'),
            ('SNDRODATA', 'SND', 'type = ro'),
            ('FXCODE', 'FXC', 'type = ro, define = yes'),
            ('VECTORS', 'VEC', 'type = ro')]
    for name, load, extra in rows:
        out += '    %-10s load = %s, %s;\n' % (name + ':', load, extra)
    return out + '}\n'


