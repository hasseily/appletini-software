def tmpdir(tag: str) -> Path:
    BUILD.mkdir(exist_ok=True)
    return Path(tempfile.mkdtemp(prefix='tmp-fxplay-%s-' % tag,
                                 dir=str(BUILD)))


def checked(setup: Setup, tag: str, part: Path = PART,
            extra=None) -> Tuple[List[str], Result, Expect]:
    """Run and compare; the run's directory deleted."""
    work = tmpdir(tag)
    try:
        res = run(setup, work, part)
        ex = expect(setup, res)
        problems = compare(setup, res, ex)
        if extra:
            problems += extra(res, ex)
        return problems, res._replace(writes=[]), ex
    finally:
        shutil.rmtree(str(work), ignore_errors=True)


def s2_alone(song: bytes, seconds: float, ntsc: bool = False,
             profile: str = PROFILE) -> Any:
    """S2's own build (build/sound65, snd_vbl) plays the song alone."""
    work = tmpdir('s2')
    try:
        variants = [v for v in profile.split('+')[1:] if v != 'ntsc']
        return run65.run(run65.Player65(SOUND65), [song],
                         [run65.start_action(0, 0, ntsc=ntsc)], seconds,
                         work, ntsc=ntsc, variants=tuple(variants),
                         profile=profile.split('+')[0])
    finally:
        shutil.rmtree(str(work), ignore_errors=True)


def same_as_s2(mine: Result, s2: Any) -> List[str]:
    """The whole AY log equal to S2's: every group (before the first
    interrupt, each interrupt, the main loop after each), write for
    write; the interrupt the run cut a prefix of S2's or the reverse; the
    chips at the end (the cut's writes aside)."""
    out = []
    if len(mine.bursts) != len(s2.bursts):
        out.append('%d interrupts, S2 %d' % (len(mine.bursts),
                                             len(s2.bursts)))
    for k in range(min(len(mine.main), len(s2.main))):
        if mine.main[k] != s2.main[k]:
            out.append('main loop after interrupt %d: %s' % (
                k, run65.first_difference(mine.main[k], s2.main[k])))
            break
        if k < min(len(mine.bursts), len(s2.bursts)) and \
                mine.bursts[k] != s2.bursts[k]:
            out.append('interrupt %d: %s' % (k + 1, run65.first_difference(
                mine.bursts[k], s2.bursts[k])))
            break
    a, b = mine.partial or [], s2.partial or []
    if a[:len(b)] != b[:len(a)]:
        out.append('the interrupt the run cut: %s, S2 %s' % (a[:3], b[:3]))
    if not a and not b and mine.state['phasor'] != s2.state['phasor']:
        out.append('the Phasor at the end differs')
    return out


def music_of(res: Result) -> List[List[Any]]:
    return [[w for w in b if w[0] != 3] for b in res.bursts]


def checkpoint(jobs: int = JOBS, quick: bool = False, part: Path = PART,
               out=print) -> List[str]:
    bank = bank_bytes()
    songs_paths = song_files()
    songs = [p.read_bytes() for p in songs_paths]
    names = [p.name.split('.')[0] for p in songs_paths]
    problems: List[str] = []
    tasks = []
    # every effect alone: PAL and NTSC, three distances, each voice
    combos = [(ntsc, vol, voice) for ntsc in (False, True)
              for vol in (VOL_NEAR, VOL_MID, VOL_FAR) for voice in 'ABC']
    if quick:
        combos = [(False, VOL_NEAR, 'A'), (True, VOL_MID, 'B'),
                  (False, VOL_FAR, 'C')]
    for ntsc, vol, voice in combos:
        tasks.append(('alone %s vol %d voice %s' % (
            'NTSC' if ntsc else 'PAL', vol, voice),
            alone_setup(bank, ntsc, vol, voice), None))
    gametics = demo3_starts()
    sel = range(len(songs)) if not quick else (0, 9, 10)
    for i in sel:
        setup = over_song_setup(songs, i, gametics)
        played = {a.args[1] for a in setup.actions if a.kind == START}
        if len(played) != 52:
            problems.append('over %s: %d of the 52 effects' % (names[i],
                                                               len(played)))
        tasks.append(('effects over %s' % names[i], setup, ('vs-s2', i)))
        tasks.append(('no effect, %s' % names[i],
                      Setup((song(0, 0),), 20.0, songs=(songs[i],)),
                      ('s2', i)))
    tasks.append(('underrun', underrun_setup(bank), 'underrun'))
    st, want = stereo_setup(bank)
    tasks.append(('stereo and mailboxes', st, ('stereo', want)))
    tone = tone_first(bank)
    tasks.append(('a tone effect before any song',
                  Setup((start(3, 0, tone),), 2.0), ('tone', tone)))
    tasks.append(('--phasor-mb-only',
                  Setup((start(3, 0, tone), other(QUERY, 3), start(5, 1, 6),
                         other(QUERY, 6), song(8, 0)), 2.0, probe=True,
                        mb_only=True, songs=(songs[0],)), 'mb'))
    for i in (0, names.index('D_INTRO')):
        tasks.append(('no effect, %s, window 512' % names[i],
                      Setup((song(0, 0),), 20.0, songs=(songs[i],),
                            profile='f121+phasor'), ('three', 'alone')))
        for prof in (PROFILE, 'f121+phasor'):
            tasks.append(('three effects over %s, %s' % (names[i], prof),
                          three_setup(songs, prof, index=i), ('three', prof)))

    def one(task):
        name, setup, kind = task
        try:
            p, res, ex = checked(setup, 'ck')
        except RunError as e:
            return name, ['run: %s' % e], None, None, kind, None
        extra = None
        if isinstance(kind, tuple) and kind[0] in ('s2', 'vs-s2'):
            extra = s2_alone(setup.songs[0], setup.seconds)
        return name, p, res, ex, kind, extra

    with ThreadPoolExecutor(max_workers=jobs) as pool:
        results = list(pool.map(one, tasks))
    hold = hold_run(songs[:3], jobs)
    for name, p, res, ex, kind, s2 in results:
        if res is not None:
            p = p + scenario_problems(kind, res, ex, s2)
        line = '%-44s %s' % (name, 'ok' if not p else p[0])
        if res is not None:
            line += '  (%d interrupts, %d chip-3 writes)' % (
                len(res.bursts), sum(1 for b in res.bursts for w in b
                                     if w[0] == 3))
        out(line)
        if res is not None and (kind in (('s2', 0), ('s2', 10)) or
                                (isinstance(kind, tuple) and
                                 kind[0] == 'three')):
            ln = sorted(irq_lengths(res))
            out('    interrupts: worst %.1f µs, median %.1f µs, p99 %.1f '
                'µs; stack %s B' % (ln[-1], statistics.median(ln),
                                    ln[int(len(ln) * 0.99)],
                                    depth(res.stack)))
        problems += ['%s: %s' % (name, x) for x in p]
    out('%-44s %s' % ('an effect held across fx_song', hold[0] or 'ok'))
    out('    ' + hold[1])
    if hold[0]:
        problems.append('hold: %s' % hold[0])
    z = sizes(part)
    out('sizes: the card part %d B (code %d, state %d) of 748 (620 and '
        'VATT\'s 128, VATT now read from bank SFX); FXCODE %d of %d B with '
        'pl_vbl; fx_service %d of 400 B' % (
            z['fx-card:FXCODE'], z['card_code'], z['card_data'], z['FXCODE'],
            z['FXC_ROOM'], z['fx:S2CODE']))
    if z['fx:S2CODE'] > 400:
        problems.append('fx_service %d B over 400' % z['fx:S2CODE'])
    if z['FXCODE'] > z['FXC_ROOM']:
        problems.append('FXCODE over its room')
    out('problems: %d' % len(problems))
    return problems


def scenario_problems(kind, res: Result, ex: Expect, s2) -> List[str]:
    out = []
    if kind == 'underrun':
        if not ex.starved:
            out.append('the ring never ran dry')
        else:
            last = max(ex.starved)
            after = [k for k in range(last + 1, len(ex.bursts) + 1)
                     if any(w[0] == 3 and w[1] >= 8 and w[2]
                            for w in ex.bursts[k - 1])]
            if not after:
                out.append('the voice never went on after its underrun')
    elif isinstance(kind, tuple) and kind[0] == 'stereo':
        want = kind[1]
        got = ['ABC'[v] for v, _, _ in ex.choices]
        if got != want:
            out.append('voices %s, the rule %s' % (''.join(got),
                                                   ''.join(want)))
    elif isinstance(kind, tuple) and kind[0] == 'tone':
        first = next((b for b in res.bursts
                      if any(w[0] == 3 for w in b)), [])
        regs = [w[1] for w in first if w[0] == 3]
        if regs != list(range(fxplay.NREGS)):
            out.append('the first burst of chip 3 wrote %s, not R0-R10' %
                       regs)
        pre = [w for g in res.main[:1] for w in g if w[0] == 3]
        if pre:
            out.append('chip 3 written before the effect: %s' % pre[:3])
    elif kind == 'mb':
        writes = [w for g in res.main for w in g if w[0] != 'reset'] + \
                 [w for b in res.bursts for w in b]
        probe = [w for w in run65.PROBE_EVENTS[True] if w[0] != 'reset']
        if writes != probe:
            out.append('AY writes beyond the probe\'s: %s' % [
                w for w in writes if w not in probe][:4])
        if res.byte('drv_nq') != 2:
            out.append('%d queries' % res.byte('drv_nq'))
        if S.FX['FX_ON'] and res.lc[S.FX['FX_ON'] - 0xC000] != 0:
            out.append('FX_ON is not 0')
    elif isinstance(kind, tuple) and kind[0] == 's2':
        out += same_as_s2(res, s2)
    elif isinstance(kind, tuple) and kind[0] == 'vs-s2':
        mine = music_of(res)
        n = min(len(mine), len(s2.bursts))
        for k in range(n):
            if mine[k] != s2.bursts[k]:
                out.append('interrupt %d: chips 0-2 %s' % (
                    k + 1, run65.first_difference(mine[k], s2.bursts[k])))
                break
    elif isinstance(kind, tuple) and kind[0] == 'three':
        d = depth(res.stack)
        if d is None or d > S.IRQ_STACK:
            out.append('the interrupt\'s stack %s B' % d)
    return out


def irq_lengths(res: Result) -> List[float]:
    return [(b - a) / res.fabric_mhz for a, b in res.times]


def hold_run(songs: Sequence[bytes], jobs: int = JOBS,
             tries: int = 40) -> Tuple[Optional[str], str]:
    """Song starts with delays swept over a frame while effects play: at
    least one VBL must land with FX_HOLD set; in it no chip-3 write; at
    the next interrupt with a voice, all of R0-R10."""
    setup = hold_setup(songs, tries)
    work = tmpdir('cal')
    try:
        res = run(setup._replace(actions=(), seconds=0.3), work)
        cal = res.byte('drv_cal') | res.byte('drv_cal', 1) << 8
    except RunError as e:
        return 'calibration: %s' % e, ''
    finally:
        shutil.rmtree(str(work), ignore_errors=True)
    setup = hold_delays(setup, cal, tries)
    try:
        p, res, ex = checked(setup, 'hold')
    except RunError as e:
        return 'run: %s' % e, ''
    if not ex.held:
        p.append('no VBL landed with FX_HOLD set (%d tries)' % tries)
    for k in ex.held:
        b = res.bursts[k - 1]
        if any(w[0] == 3 for w in b):
            p.append('interrupt %d with FX_HOLD set wrote chip 3' % k)
        nxt = next((res.bursts[j] for j in range(k, len(res.bursts))
                    if any(w[0] == 3 for w in res.bursts[j])), None)
        if nxt is not None and \
                [w[1] for w in nxt if w[0] == 3] != list(range(11)):
            p.append('after the hold of interrupt %d chip 3 got %s' % (
                k, [w[1] for w in nxt if w[0] == 3]))
    note = ('%d song starts, delay steps of %d of %d loop turns a VBL; %d '
            'VBLs landed with FX_HOLD set (interrupts %s)' % (
                tries, cal // tries, cal, len(ex.held), ex.held[:8]))
    return (p[0] if p else None), note


