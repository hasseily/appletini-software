class Act(NamedTuple):
    kind: int
    vbl: int
    args: Tuple[int, ...] = ()
    delay: int = 0

    def pack(self) -> bytes:
        a = tuple(self.args) + (0,) * (5 - len(self.args))
        return struct.pack('<BH5BH', self.kind, self.vbl, *a, self.delay)


def song(vbl, index=0, ntsc=False, loop=True, matt=0, delay=0):
    return Act(SONG, vbl, (SONG_BANK0 + index, SONG_AT & 0xFF, SONG_AT >> 8,
                           (SONG_LOOP if loop else 0) |
                           (SONG_NTSC if ntsc else 0), matt), delay)


def start(vbl, c, sound, vol=VOL_NEAR, sep=SEP_CENTRE):
    return Act(START, vbl, (c, sound, vol, sep))


def stop(vbl, c):
    return Act(STOP, vbl, (c,))


def volume(vbl, c, vol):
    return Act(VOLUME, vbl, (c, vol))


def other(kind, vbl, *args):
    return Act(kind, vbl, tuple(args))


